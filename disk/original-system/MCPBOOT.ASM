		  ;COLDSTART LOADER


FALSE	EQU  0		;DEFINE VALUE OF FALSE.
TRUE	EQU  NOT FALSE	;DEFINE VALUE OF TRUE.
MSIZE	EQU  62 	;MEMORY SIZE IN DECIMAL KB.	   
DSIDE	EQU  TRUE       ;TRUE IF SYSTEM DISKETTE IS DOUBLE SIDED.
MCP   	EQU  TRUE       ;TRUE DISABLES MCP EPROM/RAM ON BOOT(FALSE IF USING VDB
                        ;MONITOR WITH VIDEO DRIVER IN EPROM.
DDEN	EQU  TRUE       ;TRUE IF DOUB. DEN DISK.     
SPT	EQU  26 	;NUMBER OF SECTORS PER TRACK.
EXS	EQU  26 	;sectors in trk 1 , (Range = 26 to 51)
DBASE	EQU  0F8H	;DISK PORT BASE ADDRESS.	
CSTAT	EQU  03H	;CONSOLE STATUS PORT.
CDATA	EQU  02H	;CONSOLE DATA PORT.
DCOM	EQU  DBASE	;COMMAND PORT.
DSTAT	EQU  DBASE	;STATUS PORT.
TRACK	EQU  DBASE+1	;TRACK PORT.
DSECT	EQU  DBASE+2	;SECTOR PORT.
DDATA	EQU  DBASE+3	;DATA PORT.
DWAIT	EQU  DBASE+4	;WAIT PORT.
DCONT	EQU  DBASE+4	;CONTROL PORT.
CBASE	EQU  (MSIZE-20)*1024
CPMB	EQU  CBASE+3400H;START OF CP/M.
BOOTE	EQU  CPMB+1600H ;COLD BOOT ENTRY POINT.
SDS	EQU  25 	;always 25 sectors to read in trk 1.
NSECTS	EQU  SDS + EXS	;SECTORS OF CP/M.
RTCNT	EQU  10 	;NUMBER OF RETRYS.
;
	ORG  0000H	;START OF LOADER.
;
	IF   MCP	;IF USING MCP CPU.  
	MVI  A,1	;GET A 1 IN REG A.
	OUT  9		; AND DISABLE CPU ROM SLOT.
	ENDIF
;
	MVI  E,RTCNT	;GET RETRY COUNT.
BLOOP:	LXI  SP,100H	;SET STACK POINTER.
	LXI  H,CPMB	;CP/M STARTS HERE.
	MVI  D,NSECTS	;NUMBER OF SECTORS TO READ.
	MVI  C,2	;SECTOR NUMBER.
RNTRK:	MVI  B,4	;FOR HEAD LOAD.
RNSEC:	CALL READ	;READ FIRST SECTOR.
	DCR  D		;IF DONE,
	JZ   BOOTE	;GO TO CP/M.
	MVI  B,0	;FOR NO HEAD LOAD.
	INR  C		;INCREMENT SECTOR COUNT.
	MOV  A,C	;DONE WITH
SECCMP: CPI  SPT+1	;THIS TRACK?
	JC   RNSEC	;IF NOT, READ NEXT SECTOR.
;
	IF   DDEN AND NOT DSIDE 
	MVI  A,EXS + 1	;SECTORS TO READ ON TRACK 2.
	STA  SECCMP+1	;MODIFY SECTOR COMPARE VALUE.
	MVI  A,8	;GET SET DOUBLE DENSITY CODE
	OUT  DWAIT	;SET LATCH FOR D.DENSITY
	ENDIF
;
	IF   NOT DSIDE 
	MVI  A,5BH	;STEP COMMAND.
	OUT  DCOM	;ISSUE IT.
	IN   DWAIT	;WAIT UNTIL DONE.
	ENDIF
;
	IF   DSIDE	;IF DOUBLE SIDED SYSTEM.
	MVI  A,40H	;SIDE SELECT COMMAND.
	OUT  DCONT	;ISSUE IT.
	ENDIF
;
	MVI  C,1	;SECTOR NUMBER.
	JMP  RNTRK	;READ NEXT TRACK.
;
READ:
	MOV  A,C	;SECTOR IN A.
	OUT  DSECT	;SET SECTOR REGISTER.
	MVI  A,88H	;COMMAND FOR READ.
	ORA  B		;GET HEAD LOAD BIT.
	OUT  DCOM	;ISSUE COMMAND.
;
RLOOP:	IN   DWAIT	;WAIT FOR DRQ.
	ORA  A		;SET FLAGS.
	JP   CHECK	;JUMP IF DONE.
	IN   DDATA	;READ DATA.
	MOV  M,A	;PUT IN MEMORY.
	INX  H		;INCREMENT POINTER.
	JMP  RLOOP	;LOOP UNTIL DONE.
	ENDIF
;
;
CHECK:	IN   DSTAT	;READ STATUS.
	ANI  9DH	;LOOK AT ERROR BITS.
	RZ		;OK IF ZERO.
	DCR  E		;DECREMENT RETRY COUNT.
	JNZ  BLOOP	;TRY AGAIN IF NOT ZERO.
STAT:	IN  CSTAT	;PRINT ERROR IF RETRY = 0.    
	ANI 01H
	JNZ STAT
	MVI A,'E'
	OUT CDATA
HANG:	JMP HANG	;LOOP ON ERROR

	ORG  7DH	;PUT JUMP HERE.
;
	IF   DDEN AND NOT DSIDE 	;IF RUNNING DOUBLE DENSITY
	RST  0		;DO RESTART 0
	DB   0DDH	;THIS BYTE MUST BE HERE IF DOUB DEN.
	DB   0		;THIS BYTE UNUSED
	ENDIF
;
	IF   DDEN AND DSIDE 
	RST  0
	DB   0DFH
	DB   0
	ENDIF
;
	IF   NOT DDEN AND NOT DSIDE 
	RST  0		;DO WARM BOOT WITH RST INST.
	DB   0E5H
	DB   0
	ENDIF
;
	IF   NOT DDEN AND DSIDE 
	RST  0
	DB   0E7H
	DB   0
	ENDIF
;
	END   BOOT	;END OF BOOT.
