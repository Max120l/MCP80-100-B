	TITLE	'MSRDT -- MINISCRIBE RANDOM DATA TEST'

;	10-27-82



;   'MSRDT' IS A RANDOM READ/WRITE TEST DESIGNED TO ENSURE PROPER
;   OPERATION OF XCOMP CONTROLLERS WHEN USED WITH A MINISCRIBE
;   HARD DISK DRIVE.
;
;
;   NOTE -- HITTING THE "ESC" KEY WILL TERMINATE TESTING.






;	---PROGRAM CONFIGURATION---
;
;   THE FOLLOWING STATEMENTS ARE USED TO CONFIGURE THE PROGRAM.
;
;	1. TEST -- SET THIS 'FALSE' BEFORE USING THE PROGRAM.
;
;	2. S100 -- SET THIS 'TRUE' IF YOU ARE USING A CONTROLLER WITH
;	   AN S-100 BUS INTERFACE (STS). SET THIS 'FALSE' IF YOU ARE
;	   USING A CONTROLLER WITH A RIBBON CABLE INTERFACE (STR).
;
;	3. FASTKZ -- SET THIS 'TRUE' IF YOU ARE USING A MINISCRIBE HARD
;	   DISK DRIVE. SET THIS 'FALSE' IF YOU ARE NOT USING A MINISCRIBE
;	   DRIVE.
;
;		** WARNING -- SETTING 'FASTKZ' TO 'TRUE' FOR DRIVES
;			      OTHER THAN A MINISCRIBE MAY CAUSE SERIOUS
;			      MECHANICAL DRIVE FAILURES!
;
;
;	4. DRSIZE -- SET THIS TO A VALUE OF 1, 2, 3, OR 4 DEPENDING UPON
;	   THE TYPE OF DRIVE YOU ARE USING.
;
;		1 =  5 Megabyte MS-1006
;		2 = 10 Megabyte MS-1012
;		3 =  8 Megabyte MS-4010
;		4 = 20 Megabyte MS-4020
;
;
;
FALSE	EQU	0
TRUE	EQU	NOT FALSE
;
TEST	EQU	FALSE		;NOT TESTING
;
S100	EQU	TRUE		;S-100 CONTROLLER (STS)
;
FASTKZ	EQU	TRUE		;FAST RESTORE
;
DRSIZE	EQU	4		;16 MEG MS-4020




;	---EQUATES---
;
;
STRT	EQU	100H		;PROGRAM START ADDRESS
STACK	EQU	100H		;STACK POINTER
LMSK	EQU	0FFH		;LSB MASK
WBOOT	EQU	0		;CPM WARM BOOT
BDOS	EQU	5		;BDOS ENTRY POINT
DEBUG	EQU	0F000H		;DEBUG ENTRY POINT
RNCON	EQU	3619H		;CONSTANT FOR RANDOM NUMBER GENERATOR
WORST	EQU	0B6D9H		;WORST CASE DATA PATTERN
;
VSA	EQU	8		;SEEK VERIFY START ADDRESS
VCA	EQU	1BH		;SEEK VERIFY COMPARE ADDRESS
;
WRTCNT	EQU	10		;WRITE RETRY COUNT
RDCNT	EQU	10		;READ RETRY COUNT
;
DR0	EQU	41H		;DRIVE 0, HEAD 0
DATA	EQU	0E5H		;WRITE FILL DATA
RPT	EQU	80H		;REPEAT
INDEX	EQU	10H		;INDEX BIT
;
	IF	DRSIZE EQ 1	;IF 5 MEG MS-1006
MAXHD	EQU	2		;NUMBER OF HEAD
MAXCYL	EQU	306		;NUMBER OF CYLINDERS
MAXTKZ	EQU	350		;RESTORE COUNT
	ENDIF
;
	IF	DRSIZE EQ 2	;IF 10 MEG MS-1012
MAXHD	EQU	4		;NUMBER OF HEADS
MAXCYL	EQU	306		;NUMBER OF CYLINDERS
MAXTKZ	EQU	350		;RESTORE COUNT
	ENDIF
;
	IF	DRSIZE EQ 3	;IF 8 MEG MS-4010
MAXHD	EQU	2		;NUMBER OF HEADS
MAXCYL	EQU	480		;NUMBER OF CYLINDERS
MAXTKZ	EQU	511		;RESTORE COUNT
	ENDIF
;
	IF	DRSIZE EQ 4	;IF 16 MEG MS-4020
MAXHD	EQU	4		;NUMBER OF HEADS
MAXCYL	EQU	480		;NUMBER OF CYLINDERS
MAXTKZ	EQU	511		;RESTORE COUNT
	ENDIF
;
MAXSEC	EQU	32		;NUMBER OF SECTORS PER TRACK
;
;   DRIVE COMMANDS
;
STEPIN	EQU	3		;STEP DIRECTION = INWARD
STPOUT	EQU	1		;..OUTWARD
SKCMD	EQU	3		;SEEK COMMAND
NOPC	EQU	40H		;NO PRE-COMPENSATION
LOWRT	EQU	80H		;LOW WRITE CURRENT
;
;   DRIVE STATUS
;
READY	EQU	1		;DRIVE READY
WRTFLT	EQU	2		;WRITE FAULT
TK00	EQU	4		;TRACK ZERO
RAWINDX	EQU	20H		;RAW INDEX
;
;   CONTROLLER COMMANDS
;
BANK0	EQU	0		;BANK 0 SELECT
BANK1	EQU	1		;BANK 1 SELECT
DBENB	EQU	2		;DATA BUFFER ENABLE
CBENB	EQU	4		;COMPARE BUFFER ENABLE
START	EQU	8		;START COMMAND
;
;   DRIVE/CONTROLLER I/O
;
CBASE	EQU	70H		;BASE ADR OF THE CONTROLLER
;
	IF	S100	; IF S-100 BUS INTERFACE
DRCSR	EQU	CBASE		;DRIVE COMMAND/STATUS
EXTCMD	EQU	CBASE+1		;EXTENDED COMMNAND REGISTER
LOSC	EQU	CBASE+2		;SEEK COUNT, LSB
HISC	EQU	CBASE+3		;  * MSB
CTCSR	EQU	CBASE+4		;CONTROLLER COMMAND/STATUS
CTBFR	EQU	CBASE+5		;CONTROLLER BUFFER ADDRESS
CTDP	EQU	CBASE+6		;CONTROLLER DATA PORT
	ELSE		; IF RIBBON CABLE INTERFACE
DRCSR	EQU	CBASE+7		;DRIVE COMMAND/STATUS
EXTCMD	EQU	CBASE+6		;EXTENDED COMMNAND REGISTER
LOSC	EQU	CBASE+5		;SEEK COUNT, LSB
HISC	EQU	CBASE+4		;  * MSB
CTCSR	EQU	CBASE+3		;CONTROLLER COMMAND/STATUS
CTBFR	EQU	CBASE+2		;CONTROLLER BUFFER ADDRESS
CTDP	EQU	CBASE+1		;CONTROLLER DATA PORT
	ENDIF
;
;   ASCII CHARACTERS 
;
CR	EQU	0DH		;CARRIAGE RETURN
LF	EQU	0AH		;LINE FEED
BELL	EQU	7		;DING!
ESC	EQU	1BH		;ESCAPE KEY
;
;   CPM FUNCTION CODES
;
F@CI	EQU	1		;CONSOLE INPUT
F@CO	EQU	2		;CONSOLE OUTPUT
F@PRNT	EQU	9		;PRINT MESSAGES
F@RCB	EQU	10		;READ CONSOLE BUFFER
F@REQ	EQU	11		;GET CONSOLE STATUS

	PAGE



;	============
;	** MACROS **
;	============



;	---CALL BDOS---
;
;
CPM	MACRO	FC
	CALL	SYSTEM		;; SYSTEM CALL ROUTINE
	DB	FC		;; CPM FUNCTION CODE
	ENDM




;	---PRINT MESSAGES---
;
;
PRNT	MACRO	MSG
	LXI	D,MSG		;; ADR OF THE MSG
	CPM	F@PRNT		;; PRINT THE MSG
	ENDM

	PAGE

	ORG	STRT	



;	==========================
;	** PROGRAM ENTRY POINT **
;	==========================
;
;
;
BGN:	LXI	SP,STACK	;SET SP
	CALL	COFF		;STOP ANY PRIOR ACTIVITY
	PRNT	MSG1		;SAY HELLO
	MVI	A,DR0
	OUT	EXTCMD		;SLCT DRIVE 0, HEAD 0, NO PRE-COMP
	MVI	A,2
	OUT	DRCSR		;ENABLE INDEX/SECTOR/CLOCKS TO DATA BOARD
	CALL	INZVAR		;INIT VARIABLES
	CALL	FCB		;FILL CNTL BFR = ENDOP
	CALL	SRW		;SET READ/WRITE MICROCODE
;
;   COMMAND LOOP
;
LOOP:	LXI	SP,STACK	;RESET STACK PNTR
	PRNT	MSG1A		;PROMPT OPER
;
LP1:	CPM	F@REQ		;STATUS REQUEST
	JNZ	LP2		;JIF OPER HIT KEY
	LHLD	SEED
	INX	H		;INCR RANDOM NUMBER
	SHLD	SEED
	JMP	LP1
;
LP2:	MVI	A,1
	CALL	RCB		;GET OPER CMD
	CPI	'S'	
	JZ	STST		;JIF START TESTING
	CPI	'C'
	JZ	TLP		;JIF CON'T TESTING
	CPI	'X'
	JZ	XIT		;JIF EXIT TO CPM
; INVALID INPUT
INV:	PRNT	MSG19		; 'INVALID INPUT'
	JMP	LOOP		;RETRY COMMAND
;
;   EXIT TO CPM
;
XIT:	CALL	CRLF
	CALL	COFF		;TURN DRIVE/CTLR OFF
	IF	TEST
	JMP	DEBUG
	ELSE
	JMP	WBOOT		;BYE!
	ENDIF
;
;   START TESTING
;
STST:	CALL	INZVAR		;INIT VARIABLES
	CALL	TKZ		;RESTORE
	CALL	WAS		;WRITE CYL 0, HEAD 0, SECTOR 0
;
;   TEST LOOP
;
TLP:	PRNT	MSG25		; 'TESTING'
;
TLP1:	CALL	RNG		;GET RANDOM NUM
	LXI	D,MAXCYL
	CALL	DIVIDE		;DIVIDE TO FORM RANDOM CYLINDER
	XCHG
	SHLD	CYL		;PICK RANDOM CYL
	CALL	RNG		;GET RANDOM NUM
	LXI	D,MAXHD
	CALL	DIVIDE		;DIVIDE TO FORM RANDOM HEAD
	MOV	A,E
	STA	HEAD		;PICK RANDOM HEAD
	CALL	RNG		;GET RANDOM NUM
	LXI	D,MAXSEC
	CALL	DIVIDE		;FORM SECT ADR
	MOV	A,E
	STA	SECTOR		;PICK RANDOM SECTOR
	CALL	WAS		;WRITE A SECTOR
	CALL	RAS		;READ PREVIOS SECTOR
	LXI	H,PASS
	CALL	BUMP		;BUMP PASS COUNT
	LXI	H,CYL
	LXI	D,OLDCYL
	MVI	B,4
	CALL	MOVE		;MAKE CURRENT RANDOM ADR INTO OLD ADR
	CALL	STOP		;STOP TESTING ?  (RIF NO)
	JMP	TLP1		;KEEP GOING

	PAGE




;	=============================
;	** FORMAT, WRITE, & VERIFY **
;	=============================




;	---WRITE A SECTOR---
;
;
WAS:	MVI	A,WRTCNT
	STA	RETRY		;SET WRITE RETRY COUNT
	LXI	H,CYL
	LXI	D,TCYL
	MVI	B,4
	CALL	MOVE		;MAKE CURRENT DISK ADR INTO TARGET
	CALL	PUTHDR		;PUT HDR INFO INTO DATA BFR
	CALL	SEEK		;SEEK TO NEW CYL
;
WAS1:	LXI	H,WTBL
	CALL	DORW		;WRITE A SECTOR
	JZ	WAS2		;JIF WRITE OK
	LXI	H,RETRY
	DCR	M		;DECR RETRY COUNT
	JNZ	WAS1		;JIF RETRY WRITE
	LXI	D,MSG10		; 'WRITE ERROR'
	CALL	PEM		;PRINT ERROR MSG
	LXI	H,HWERR
	JMP	BUMP		;BUMP HARD WRITE ERROR COUNT, EXIT
;
WAS2:	LDA	RETRY
	SUI	WRTCNT
	RZ			;RIF NO SOFT ERRORS
	LXI	H,SWERR
	JMP	BUMP		;BUMP SOFT ERR CNT, EXIT






;	---READ A SECTOR---
;
;
RAS:	MVI	A,RDCNT
	STA	RETRY		;SET RETRY COUNT
	LXI	H,OLDCYL
	LXI	D,TCYL
	MVI	B,4
	CALL	MOVE		;MAKE OLD DISK ADR INTO TARGET
	CALL	SEEK		;SEEK TO NEW CYL
;
RAS1:	LXI	H,RTBL
	CALL	DORW		;READ THE SECTOR
	JZ	RAS2		;JIF READ OK
	LXI	H,RETRY
	DCR	M		;DECR RETRY COUNT
	JNZ	RAS1		;JIF RETRY READ
	LXI	D,MSG11
	CALL	PEM		;PRINT ERR MSG
	LXI	H,HRERR
	JMP	BUMP		;BUMP HARD READ ERROR CNT, EXIT
;
RAS2:	CALL	TSTHDR		;TEST HDR INFO (IN DATA BFR)
	JZ	RAS3		;JIF DATA OK
	LXI	D,MSG8		; 'VERIFY ERROR'
	CALL	PEM		;PRINT ERROR MSG
	LXI	H,DVERR
	CALL	BUMP		;BUMP VERIFY ERROR CNT
;
RAS3:	LDA	RETRY
	SUI	RDCNT
	RZ			;RIF NO SOFT ERRORS
	LXI	H,SRERR
	JMP	BUMP		;BUMP SOFT READ ERROR CNT, EWXIT

	PAGE


;	============================
;	** DISK RELATED FUNCTIONS **
;	============================




;	---EXECUTE READ/WRITE COMMANDS---
;
;
DORW:	CALL	RDY		;DRIVE READY ?  (RIF YES)
	MOV	A,M
	OUT	CTCSR		;ENB CMP BFR
	INX	H
	MOV	A,M
	OUT	CTBFR		;SET CMP BFR ADR
	INX	H
;
	XCHG			;D/E = TBL ADR
	LXI	H,TCYL		;TARGET DISK ADR
	MVI	B,4
DO1:	MOV	A,M
	OUT	CTDP		;PUT HDR INFO INTO CMP BFR
	INX	H
	DCR	B
	JNZ	DO1
	XCHG			;H/L = TBL ADR
;
	MOV	A,M		;A = CNTL BANK
	INX	H
	MOV	B,A
	OUT	CTCSR		;SLCT CNTL BANK
	MOV	A,M
	OUT	CTBFR		;SET START ADR
	INX	H
	MOV	A,B
	ORI	START
	OUT	CTCSR		;START R/W CMD
;
DO2:	CALL	WFD		;WAIT FOR CMD TO FINISH
	STA	CSTAT		;SAVE CTLR STATUS
	ANA	M		;TEST CTLR STATUS (0=OK)
	MOV	B,A
	IN	DRCSR		;DRIVE STATUS
	STA	DSTAT		;  SAVE IT
	ANI	WRTFLT		;WRITE FAULT ?
	CNZ	CLRDF		;CIF CLEAR DRIVE FAULT
	ORA	B		;SET/CLEAR ERROR FLAG (0=OK)
	RET




;	---WAIT FOR DONE---
;
;
WFD:	PUSH	H		;SAVE H/L
	LXI	H,0		;DELAY COUNT
;
WFD1:	IN	CTCSR		;CTLR STATUS
	RRC
	JC	WFD2		;JIF READ/WRITE DONE
	DCX	H		;DECR DELAY COUNT
	MOV	A,H
	ORA	L
	JNZ	WFD1		;JIF CON'T WAITING
	OUT	CTCSR		;STOP THE CTLR
	PRNT	MSG24		; 'READ/WRITE FAILED'
	CALL	REPORT		;DISPLAY COUNTS
	JMP	LOOP		;ABORT
;
WFD2:	POP	H		;RESTORE H/L
	IN	CTCSR		;GET NON-CHANGING STATUS
	MOV	B,A		;..SAVE IT
	XRA	A
	OUT	CTCSR		;STOP CTLR
	MOV	A,B
	RET




;	---REZERO---
;
;
	IF	FASTKZ		;FAST RESTORE ALGORITHM

TKZ:	IN	DRCSR		;DRIVE STATUS
	ANI	TK00		;TRACK ZERO FLAG
	RNZ			;RIF ALREADY AT TRACK ZERO
;
	CALL	RDY		;DRIVE READY ?  (RIF YES)
	MVI	A,MAXTKZ AND LMSK
	OUT	LOSC		;SET LSB OF SEEK COUNT
	MVI	A,MAXTKZ SHR 8
	OUT	HISC		;SET MSB
	MVI	A,STPOUT
	OUT	EXTCMD		;SET SEEK DIRC = OUTWARD
	MVI	A,SKCMD
	OUT	DRCSR		;ISSUE SEEK CMD
	LXI	H,0
	MVI	B,10
;
TKZ1:	IN	DRCSR		;DRIVE STATUS
	ANI	TK00		;TRACK ZERO FLAG
	JNZ	TKZ2		;JIF AT TRACK ZERO
	DCX	H		;DECR TIME-OUT
	MOV	A,H
	ORA	L
	JNZ	TKZ1
	DCR	B
	JNZ	TKZ1
	OUT	HISC
	OUT	LOSC		;ZERO SEEK COUNTER
	PRNT	MSG6		; 'RESTORE FAILED'
	CALL	PDS		;PRINT DRIVE STATUS
	CALL	CRLF		;DO CR.LF
	JMP	LOOP		;ABORT
;
TKZ2:	XRA	A
	OUT	HISC
	OUT	LOSC		;ZERO SEEK COUNTER
	JMP	WSC		;WAIT FOR SEEK DONE, EXIT

	ENDIF



	IF	NOT FASTKZ	;NORMAL RESTORE ALGORITHM

TKZ:	LXI	B,MAXTKZ	;SET FIND COUNT
;
TKZ1:	CALL	RDY		;DRIVE READY ?  (RIF YES)
	IN	DRCSR		;DRIVE STATUS
	ANI	TK00		;TRACK ZERO INDICATOR
	RNZ			;RIF AT TRACK ZERO
	DCX	B		;DECR FIND COUNT
	MOV	A,B
	ORA	C
	JZ	TKZ2		;JIF REZERO FAILED
	XRA	A
	OUT	HISC
	INR	A
	OUT	LOSC		;SET SEEK COUNT = 1
	OUT	EXTCMD		;SET DIRC = OUT
	MVI	A,SKCMD
	OUT	DRCSR		;ISSUE SEEK CMD
	CALL	WSC		;WAIT FOR SEEK DONE
	JMP	TKZ1
;
TKZ2:	PRNT	MSG6		; 'REZERO FAILED'
	CALL	PDS		;PRINT DRIVE STATUS
	CALL	CRLF		;DO CR.LF
	JMP	LOOP		;ABORT

	ENDIF




;	---SEEK TO TRACK ZERO---
;
;
STZ:	LXI	H,0
	SHLD	TCYL		;SET CYL ADR = 0
				;  * FALL THRU TO 'SEEK'





;	---SEEK---
;
;
SEEK:	MVI	A,3
	STA	SKRTC		;SET RETRY COUNT
;
SEK1:	CALL	RDY		;DRIVE READY ?  (RIF YES)
	LHLD	TCYL		;TARGET CYL
	XCHG
	LHLD	CCA		;CURRENT CYL ADR
	CALL	SUBT		; (H/L) - (D/E)
	JZ	HDSEL		;NO NEED TO SEEK, BUT SLCT NEW HEAD
	RAL			;CY = +/-
	JNC	SEK2		;JIF SEEK OUTWARD
; SEEK INWARD
	MOV	A,L		;MAKE SEEK COUNT POSITIVE
	CMA			  ;
	MOV	L,A		  ;
	MOV	A,H		  ;
	CMA			  ;
	MOV	H,A		  ;
	INX	H		  ;
	MVI	A,STEPIN
	OUT	EXTCMD		;SET SEEK DIRC = INWARD
	JMP	SEK3		;DO SEEK
; SEEK OUTWARD
SEK2:	MVI	A,STPOUT
	OUT	EXTCMD		;SET SEEK DIRC = OUTWARD
; 
SEK3:	MOV	A,L
	OUT	LOSC		;SET SEEK COUNT, LSB
	MOV	A,H
	OUT	HISC		;   * MSB
	MVI	A,3
	OUT	DRCSR		;START SEEK CMD
	LHLD	TCYL
	SHLD	CCA		;UPDATE CURR CYL ADR
	CALL	WSC		;WAIT FOR SEEK DONE
; SEEK VERIFY
	MVI	A,3
	STA	VSRTC		;SET RETRY COUNT
	MVI	A,CBENB
	OUT	CTCSR		;ENABLE BANK ZERO CMP BFR
	MVI	A,VCA
	OUT	CTBFR		;SET CMP BFR ADR
	LHLD	CCA		;CURR CYL ADR
	MOV	A,L
	OUT	CTDP		;SET CYL ADR, LSB
	MOV	A,H
	OUT	CTDP		;SET CYL ADR, MSB
SEK4:	MVI	A,VSA
	OUT	CTBFR		;SET M/CODE START ADR
	MVI	A,START
	OUT	CTCSR		;START VERIFY
	CALL	WFD		;WAIT FOR DONE
	ANI	0CH		;TEST CTLR STATUS
	JZ	HDSEL		;VERIFY OK...SLCT HEAD, EXIT
	LXI	H,VSRTC
	DCR	M		;DECR RETRY COUNT
	JNZ	SEK4		;JIF RETRY SEEK VERIFY
; VERIFY FAILED
	LXI	H,SKERR
	CALL	BUMP		;INCR SEEK ERROR COUNT
	CALL	TKZ		;RESTORE
	LXI	H,0
	SHLD	CCA		;SET CURR CYL ADR = 0
	LXI	H,SKRTC
	DCR	M		;DECR RETRY COUNT
	JNZ	SEK1		;JIF RETRY SEEK
; UNRECOVERABLE SEEK ERROR
	PRNT	MSG21		; 'SEEK FAILED'
	LHLD	TCYL
	CALL	P3D		;PRINT CYL ADR
	CALL	CRLF		;DO CR.LF
	JMP	LOOP		;ABORT




;	---WAIT FOR SEEK COMPLETE---
;
;
WSC:	LXI	H,0		;DELAY COUNT
	MVI	B,3
;
WSC1:	IN	DRCSR		;DRIVE STATUS
	RAL
	JC	WSC2		;JIF SEEK DONE
	DCX	H		;DECR DELAY COUNT
	MOV	A,H
	ORA	L
	JNZ	WSC1		;JIF CON'T WAITING
	DCR	B
	JNZ	WSC1		;JIF CON'T WAITING
	PRNT	MSG23		; 'SEEK FAILED'
	CALL	REPORT		;DISPLAY COUNTS
	JMP	LOOP		;ABORT
;
WSC2:	RAR
	STA	DSTAT		;SAVE DRIVE STATUS
	RET




;	---HEAD SELECT---
;
;
HDSEL:	LDA	THEAD		;TARGET HEAD
	RLC			;SHIFT FOR H/W
	RLC
	ORI	1		;TO MAINTAIN DRIVE SLCT
	IF	DRSIZE LT 3	;IF USING MS-1006 OR MS-1012
	MOV	B,A
	LHLD	TCYL		;TARGET CYL ADR
	LXI	D,MAXCYL/2
	CALL	SUBT		; (H/L) - (D/E)
	RAL			;CY = +/-
	MVI	A,0		;ALWAYS PRE-COMP
	JC	HDS1		;JIF CYL < HALF WAY
	MVI	A,LOWRT		;LOW WRITE CURRENT
HDS1:	ORA	B		;B = HEAD SLCT INFO
	ENDIF
	OUT	EXTCMD		;SELECT THE HEAD
	RET




;	---DRIVE READY TEST---
;
;
RDY:	IN	DRCSR		;DRIVE STATUS
	RRC
	RC			;RIF DRIVE READY
	PRNT	MSG12		;PRINT ERROR MSG
	JMP	LOOP		;ABORT




;	---CLEAR DRIVE FAULT---
;
;
CLRDF:	XRA	A
	OUT	EXTCMD		;DE-SELECT THE DRIVE
	JMP	HDSEL		;RE-SELECT DRIVE & CORRECT HEAD




;	---FILL CONTROL BUFFER---
;
;
FCB:	XRA	A
	OUT	CTCSR		;SLCT CNTL BANK0
	OUT	CTBFR		;SET BFR ADR = 0
	MVI	B,128		;LOOP COUNT
	MVI	A,0FH		;ENDOP
FCB1:	OUT	CTDP		;PUT ENDOP INTO BANK0 CNTL BFR
	DCR	B
	JNZ	FCB1
;
	MVI	A,1
	OUT	CTCSR		;SLCT CNTL BANK1
	MVI	A,0FH
	MVI	B,128
FCB2:	OUT	CTDP		;PUT ENDOP INTO BANK1 CNTL BFR
	DCR	B
	JNZ	FCB2
	RET




;	---SET READ/WRITE MICROCODE---
;
;
SRW:	LXI	H,RDCODE
	CALL	SQUIRT		;SET READ M/CODE
	LXI	H,WRTCODE
	JMP	SQUIRT		;SET WRITE M/CODE, EXIT




;	---PUT HEADER INFO INTO DATA BUFFER---
;
;
PUTHDR:	CALL	STP		;SET TEST PAMS
;
PH1:	MOV	A,M
	OUT	CTDP		;OUTPUT HDR INFO
	INX	H
	DCR	B
	JNZ	PH1
; FILL REST OF BFR WITH WORST CASE DATA
	LXI	H,WORST		;WORST CASE DATA PATTERN
	MVI	B,(256-4)/2	;LOOP COUNT
PH2:	MOV	A,L
	OUT	CTDP
	MOV	A,H
	OUT	CTDP
	DCR	B
	JNZ	PH2
	RET




;	---TEST HEADER INFO (IN DATA BUFFER)---
;
;
TSTHDR:	CALL	STP		;SET TEST PAMS
	IN	CTDP		;PRIME INPUT DATA
	NOP			;TIME DELAY
;
TH1:	IN	CTDP		;GET DATA FROM BFR
	CMP	M
	RNZ			;RIF COMPARE ERROR
	INX	H
	DCR	B
	JNZ	TH1
	RET			;EXIT, DATA COMPARES




;	---SET TEST PARAMETERS----
;
;
STP:	MVI	A,DBENB
