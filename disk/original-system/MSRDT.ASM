	INX	H
	DCR	B
	JNZ	INZ1
	RET




;	---READ CONSOLE BUFFER---
;
;   READS A STRING OF ASCII CHARACTERS. LOWER CASE CHARACTERS ARE
;   TRANSLATED TO UPPER CASE. USES THE CPM 'READ BUFFER' FUNCTION.
;
;
;	ENTRY:	A = INPUT CHARACTER COUNT
;
;	EXIT:	A = FIRST CHARACTER IN THE STRING
;	      D/E = BUFFER ADDRESS OF THE FIRST CHARACTER
;
;
;   ERRORS - - IF AN ERROR OCCURES, 'RCB' IS ABORTED & THE
;	       PROGRAM RESUMES RUNNING AT 'LOOP'.
;
;
RCB:	LXI	D,RDBFR		;READ BFR
	INR	A		;FOR N+1 CHARS
	STAX	D		;SET CHAR COUNT
	MOV	B,A		;..SAVE THE COUNT
	CPM	F@RCB		;READ THE STRING
	CALL	CRLF		;DO CR.LF
	LXI	H,RDBFR+1
	MOV	A,M		;A = INPUT CHAR COUNT
	ORA	A
	JZ	INV		;ERROR, NO CHARS INPUT
	CMP	B		;B = MAX CHAR CNT +1
	JNC	INV		;ERROR, TOO MANY INPUT CHARS
; CONVERT L/C TO U/C
	MOV	B,A		;B = # CHARS TO CONVERT
RCB1:	INX	H		;INCR BFR ADR
	MOV	A,M
	CALL	UCT		;CONVERT
	MOV	M,A
	DCR	B
	JNZ	RCB1
	LXI	D,RDBFR+2	;D/E = ADR OF 1ST CHAR IN STRING
	LDAX	D		;..GET IT
	RET




;	---UPPER CASE TRANSLATION---
;
;   CONVERTS LOWER CASE CHARACTERS TO UPPER CASE.
;
;
UCT:	ANI	7FH		;KILL PARITY BIT
	CPI	61H
	RC			;RIF NOT L/C CHAR
	CPI	7BH	
	RNC			;RIF NOT L/C CHAR
	SUI	20H		;DO CONVERSION
	RET




;	---RANDOM NUMBER GENERATOR---
;
;
RNG:	PUSH	D
	PUSH	B		;SAVE REGS
	LHLD	SEED		;CURRENT RANDOM NUMBER
	MOV	D,H
	MOV	E,L		;COPY TO D/E
	MVI	B,11
RNG1:	DAD	H		;SHIFT H/L LEFT 11 TIMES
	DCR	B
	JNZ	RNG1
	DAD	D		;ADD ORIG #
	DAD	H
	DAD	H		;SHIFT LEFT TWICE
	DAD	D		;ADD ORIG #
	LXI	D,RNCON
	DAD	D		;ADD CONSTANT
	SHLD	SEED		;SAVE NEW RANDOM NUMBER
	POP	B
	POP	D		;RESTORE REGS
	MOV	A,H		;MSB MOST RANDOM
	RET





;	---DIVIDE---
;
;   ENTRY:	H/L = DIVIDEND
;		D/E = DIVISOR
;
;   EXIT:	H/L = QUOTIENT
;		D/E = REMAINDER
;
;
DIVIDE:	XRA	A		;CLEAR SHIFT COUNT
	XCHG			;H/L = DIVISOR
;
DIV1:	INR	A		;INCR SHIFT COUNT
	DAD	H		;SHIFT H/L LEFT UNTIL A ONE
	JNC	DIV1		;  BIT DROPS OFF THE END
	XCHG
	MOV	C,E
	MOV	B,D		;B/C = DIVISOR
	LXI	D,0		;CLEAR QUOTIENT
;
DIV2:	PUSH	PSW		;SAVE SHIFT COUNT
	MOV	A,B		;  (CY SET 1ST TIME ONLY)
	RAR
	MOV	B,A
	MOV	A,C
	RAR
	MOV	C,A		;SHIFT DIVISOR RIGHT
	MOV	A,E
	STC
	RAL
	MOV	E,A
	MOV	A,D
	RAL
	MOV	D,A		;SHIFT QUOTIENT LEFT, SET LSB
	MOV	A,L
	SUB	C
	MOV	L,A
	MOV	A,H
	SBB	B
	MOV	H,A		;DIVIDEND = DIVIDEND - DIVISOR
	JNC	DIV3		;JIF NO BORROW
	DAD	B		;RESTORE DIVIDEND
	DCR	E		;CLEAR LSB OF QUOTIEENT
;
DIV3:	POP	PSW		;A = SHIFT COUNT
	ORA	A		;CLEAR CY
	DCR	A		;DECR SHIFT COUNT
	JNZ	DIV2		;JIF MORE TO DO
	XCHG
	RET




;	---16 BIT SUBTRACTION---
