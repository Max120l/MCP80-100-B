;	TITLE	'MSIOS -- MINISCRIBE CBIOS FOR CPM 2.2'
;       ***** MCP COMPUTER PRODUCTS CONFIGURATION *****
;	12-01-82




;   'MSIOS' IS THE I/O DRIVER FOR CPM 2.2 USING A MINISCRIBE HARD DISK
;   DRIVE & AN XCOMP STS/STR DISK CONTROLLER. DRIVES ARE CONFIGURED AS
;   FOLLOWS:
;
;	MS-1006 = ONE 5 MEGABYTE DRIVE
;	MS-1012 = TWO 5 MEGABYTE DRIVES
;	MS-4010 = ONE 7.8 MEGABYTE DRIVE
;	MS-4020 = TWO 7.8 MEGABYTE DRIVES
;
;   'MSIOS' ALSO SUPPORTS TWO FLOPPY DISK DRIVES USING A MCP/FDC
;   F/D CONTROLLER (SINGLE OR DOUBLE DENSITY MODE ).
;
;
;
;   MS-1006/MS-4010 CONFIGURATION:
;
;	A: = HARD DISK
;	B: = FLOPPY DISK, DRIVE 0
;	C: =    "    "      "   1
;
;
;
;   MS-1012/MS-4020 CONFIGURATION;
;
;	A: = HARD DISK, LOGICAL DRIVE 0
;	B: =  "    "       "      "   1
;	C: = FLOPPY DISK, DRIVE 0
;	D: =   "     "      "   1





;	---PROGRAM CONFIGURATION---
;
;
;   THE FOLLOWING STATMENTS ARE USED TO CONFIGURE THE PROGRAM.
;
;	1. TEST -- SET THIS 'FALSE' BEFORE USING THE PROGRAM.
;
;	2. Z80 -- SET THIS "TRUE" IF YOU ARE USING A Z-80 MICROPROCESSOR.
;	   THIS WILL SPEED UP DATA TRANSFERS TO/FROM THE CONTROLLER
;	   BUFFER.
;
;	3. S100 -- SET THIS "TRUE" IF YOU ARE USING A CONTROLLER WITH
;	   AN S-100 BUS INTERFACE (STS). SET THIS "FALSE" IF YOU ARE
;	   USING A CONTROLLER WITH A RIBBON CABLE INTERFACE (STR).
;
;	4. FASTKZ -- SET THIS 'TRUE' IF YOU ARE USING A MINISCRIBE HARD
;	   DISK DRIVE. SET THIS 'FALSE' IF YOU ARE NOT USING A MINISCRIBE
;	   DRIVE.
;
;		** WARNING -- SETTING 'FASTKZ' TO 'TRUE' FOR DRIVES
;			      OTHER THAN A MINISCRIBE MAY CAUSE SERIOUS
;			      MECHANICAL DRIVE FAILURES!
;
;
;	5. DRSIZE -- SET THIS TO A VALUE OF 1, 2, 3, OR 4 DEPENDING UPON
;	   THE TYPE OF DRIVE YOU ARE USING.
;
;		1 =  5 Megabyte MS-1006
;		2 = 10 Megabyte MS-1012
;		3 =  8 Megabyte MS-4010
;		4 = 20 Megabyte MS-4020
;
;
;
;
