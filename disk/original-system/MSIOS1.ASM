	DW	1023		;DRM: (DIR SIZE) - 1
	DB	0FFH		;AL0: DIRECTORY ALLOCATION BITS, MSB
	DB	0FFH		;AL1:   * LSB
	DW	0		;CKS: CHECK SIZE
	DW	2		;OFF: TRACK OFFSET
	ENDIF
;
	IF	DRSIZE GT 2	;IF USING MS-4010 OR MS-4020
	DW	2*MAXSEC	;SPT: SECTORS PER TRACK
	DB	5		;BSH: BLOCK SHIFT FACTOR
	DB	31		;BLM: BLOCK MASK
	DB	0		;EXM: NULL MASK
	DW	1915		;DSM: (DISK SIZE) - 1
	DW	1023		;DRM: (DIR SIZE) - 1
	DB	0FFH		;AL0: DIRECTORY ALLOCATION BITS, MSB
	DB	0		;AL1:   * LSB
	DW	0		;CKS: CHECK SIZE
	DW	2		;OFF: TRACK OFFSET
	ENDIF




