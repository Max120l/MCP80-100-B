;
;
SUBT:	MOV	A,L
	SUB	E		;LSB
	MOV	L,A
	MOV	A,H
	SBB	D		;MSB
	MOV	H,A
	ORA	L		;TEST FOR ZERO RESULTS
	MOV	A,H		;FOR EXTERNAL USE
	RET




