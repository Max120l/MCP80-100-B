;	---COLD BOOT---
;
;
BOOT:	LXI	SP,BUFF		;USE LOW MEMORY
	LXI	H,HELLO
	CALL	PRNT		;SAY HELLO
	CALL	INIT		;INIT FLAGS & VARIABLES
	STA	CDISK		;FOR USE BY CPM
	JMP	XIT		;GOTO CPM




;	---WARM BOOT---
;
;
WBOOT:  LXI     H,0             ;CLEAR FLOPPY DENSITY FLAGS
        SHLD    DRVFLG          ;FOR MCP
        SHLD    DRVFLG+2

      	LXI	SP,BUFF
	XRA	A
	STA	R@DSK		;SLCT DRIVE ZERO
;
	CALL	XSTZ		;SEEK TO TRACK ZERO
	LXI	H,CPM		;CPM LOAD ADR
	SHLD	DMADR		;  SAVE IT
	MVI	C,2
	CALL	SETSEC		;SET SECTOR ADR
	MVI	A,NSECT		; # SECTORS TO WARM BOOT
;
WB1:	STA	SECNT		;SAVE THE SECTOR COUNT
	CALL	HDREAD		;READ A SECTOR FROM THE HARD DISK
	ORA	A
	JZ	WB2		;JIF READ OK
	LXI	H,MSG1		;  'CAN'T BOOT'
	CALL	PRNT		;PRINT ERROR MSG
	CALL	CI		;WAIT FOR OPER
	CALL	CRLF
	JMP	WBOOT		;TRY ANOTHER BOOT
;
WB2:	LHLD	DMADR
	LXI	D,128
	DAD	D		;BUMP DMA ADR
	SHLD	DMADR
	LXI	H,R@SEC
	MOV	C,M
	INR	C		;INCR SECT ADR
	CALL	SETSEC		;SET NEW SECT ADR
	LDA	SECNT		;A = SECTOR COUNT
	DCR	A
	JNZ	WB1		;JIF MORE TO READ




;	---EXIT TO CPM---
;
;
XIT:	LXI	H,BUFF
	SHLD	DMADR		;INIT DMA ADR
	MVI	A,0C3H		;JMP INST
	STA	0
	LXI	H,WBX
	SHLD	1		;SET WARM BOOT LINK
	LXI	H,BDOS
	STA	5
	SHLD	6		;SET BDOS LINK
	LDA	CDISK		;CURRENT LOGGED-IN DISK & USER
	MOV	C,A
	JMP	CPM		;GOTO CPM




;	---CONSOLE INPUT---
;
;
CI:	IN	CRTS		;CRT STATUS
	ANI	CRTDA		;DATA AVAIL
	JZ	CI		;WAIT FOR DATA
	IN	CRTD		;CRT DATA
	ANI	7FH		;KILL PARITY BIT
	IF	TEST		;IF WE ARE TESTING
	CPI	'~'
	RNZ			;RIF NOT DEBUG TRAP CHAR
	CALL	TRAP		;TRAP TO ROM DEBUG
	JMP	CI		;GET NEXT CHAR
	ELSE			;IF NOT TESTING
	RET
	ENDIF




;	---CONSOLE OUTPUT---
;
;
CO:	IN	CRTS		;CRT STATUS
	ANI	CRTBE		;BFR EMPTY
	JZ	CO		;WAIT FOR EMPTY
	MOV	A,C
	OUT	CRTD		;OUTPUT DATA
	RET





;	---CONSOLE STATUS---
;
;
CSTS:	IN	CRTS		;CRT STATUS
	ANI	CRTDA		;DATA AVAIL
	RZ			;RIF NOT AVAIL
	ORI	-1		;SET AVAIL FLAG
	RET





;	---LIST OUTPUT---
;
;
LO:	IN	LPS		;L/P STATUS
	ANI	LPXR		;XMTR RDY
	XRI	LPXR		;INVERT BOTH BITS
	JNZ	LO		;WAIT FOR RDY
	MOV	A,C
	OUT	LPD		;OUTPUT PRINT DATA
	RET





;	---READER INPUT---
;
;
RDR:	MVI	A,EOF		;NO RDR -- SET 'EOF' FLAG
	RET





;	---PUNCH OUT---
;
;
PO:	RET			;  * NOT IMPLEMENTED *





;	---LIST READY TEST---
;
;
LOTST:	IN	LPS		;L/P STATUS
	ANI	LPXR		;XMTR RDY
	XRI	LPXR		;INVERT BOTH BITS
	MVI	A,0
	RNZ			;RIF NOT RDY
	ORI	-1		;SET READY FLAG
	RET





;	---SECTOR TRANSLATE ROUTINE---
;
;
SXR:	XCHG			;H/L = ADR OF XLATE TABLE
	MOV	A,L
	ORA	H		;TEST TABLE ADR
	JNZ	SXR1		;JIF DO XLATE
	DAD	B		;DON'T XLATE -- USE SECT ADR AS IS
	RET
;
SXR1:	DAD	B		;INDEX INTO THE TABLE
	MOV	L,M		;L = XLATED SECTOR ADR
	MVI	H,0		;H = 0 FOR 16-BIT VALUE
	RET





;	---HOME---
;
;
HOME:	LDA	R@DSK		;DRIVE #
	CPI	MAXHD
	JC	XSTZ		;JIF REZERO HARD DISK
	CPI	LLD
	JC	FHOME		;JIF REZERO FLOPPY
;
;   SET ERROR FLAG
;
SEF:	MVI	A,1		;A = ERROR CODE
	ORA	A		;SET 8080/Z80 FLAGS
	RET





;	---READ---
;
;
READ:	LDA	R@DSK		;DRIVE #
	CPI	MAXHD
	JC	HDREAD		;JIF READ FROM H/D
	CPI	LLD
	JC	FREAD		;JIF READ FROM F/D
	JMP	SEF		;ABORT, SELECT ERROR





;	---WRITE---
;
;
WRITE:	LDA	R@DSK		;DRIVE #
	CPI	MAXHD
	JC	HDWRT		;JIF WRITE ONTO H/D
	CPI	LLD
	JC	FWRT		;JIF WRITE ONTO F/D
	JMP	SEF		;ABORT, SELECT ERROR





;	---SET DRIVE NUMBER---
;
;
SETDR:	MOV	A,C		;A = NEW DRIVE #
	STA	R@DSK		;  SAVE IT
	LXI	H,0
	CPI	LLD
	RNC			;RIF INVALID DRIVE #
        LDA     R@DSK
        CPI     MAXHD
        JC      DSEL
        JMP     FSEL
DSEL:   MOV     L,A
	DAD	H		;SHIFT H/L LEFT 4
	DAD	H		;   (HL = HL*16)
	DAD	H
	DAD	H
	LXI	D,DPHDR		;DISK PARM HDR
	DAD	D		;H/L = DPHDR FOR SELECTED DRIVE
	RET





;	---SET SECTOR ADR---
;
;
SETSEC:	MOV	A,C
	STA	R@SEC		;SAVE SECTOR ADR
; SET REAL SECTOR ADR FOR THE H/D DRIVER
	ANI	NOT 1		;CLEAR LOW ORDER BIT
	RRC			;THERE ARE 2 CPM SECTORS PER H/D SECT
	STA	RSA		;SAVE REAL SECTOR ADR
	RET





;	---SET TRACK ADDRESS---
;
;
SETTK:	MOV	H,B
	MOV	L,C
	SHLD	R@TRK		;SAVE TRACK ADR
	RET





;	---SET DMA ADDRESS---
;
;
SETDMA:	MOV	H,B
	MOV	L,C
	SHLD	DMADR		;SAVE DMA ADR
	RET

	PAGE


;	======================================
;	** HARD DISK BLOCK/DEBLOCK ROUTINES **
;	======================================




;	---HARD DISK READ---
;
;
HDREAD:	XRA	A
	STA	ERFLG		;CLEAR THE ERROR FLAG
	SETBIT	F@RDOP		;SET READ OPERATION FLAG
	TSTBIT	F@WIP		;WRITE IN PROGRESS ?
	CNZ	XWRT		;YES, WRITE DATA BEFORE READ
	CLRBIT	F@WIP		;RESET 'WIP' FLAG
	CALL	TSTHST		;HOST = REQ ?
	JNZ	HDRD1		;NO, READ A BLOCK
	TSTBIT	F@RIP		;PRIOR BLOCK READ ?
	JNZ	HDRD2		;YES, JUST EXTRACT DATA FROM BFR
HDRD1:	CALL	SETHST		;MAKE HOST=REQ
	CALL	XREAD		;READ A BLOCK
HDRD2:	CALL	GETDMA		;GET DMA ADR, SET POINTERS
	CALL	BFRIN		;MOVE DATA TO RAM
	SETBIT	F@RIP		;SET READ-IN-PROGRESS FLAG
	LDA	ERFLG		;ERROR FLAG
	RET




;	---HARD DISK WRITE---
;
;
HDWRT:	XRA	A
	STA	ERFLG		;CLEAR THE ERROR FLAG
	CLRBIT	F@RIP		;CLEAR READ-IN-PROGRESS FLAG
	MOV	A,C		;A = WRITE MODE
	DCR	A
	JZ	WDIR		;DO DIRECTORY WRITE
	JM	WNORM		;DO NORMAL WRITE
;
;   UNALLOCATED WRITE
;
WUN:	TSTBIT	F@WIP		;WRITE IN PROGRESS ?
	CNZ	XWRT		;YES, WRITE DATA IN BFR
; SET UNALLOC RECORD PARAMETERS
	MVI	A,BLKSIZ/128
	STA	U@CNT		;SET UNALLOC RECORD COUNT
	LHLD	R@DSK
	SHLD	U@DSK		;UPDATE DRIVE & SECTOR
	LHLD	R@TRK
	SHLD	U@TRK		;UPDATE TRACK ADR
	CALL	SETHST		;SET HOST = REQ
	CALL	BUMP		;BUMP UNALC PARMS FOR NEXT PASS

; XFER DATA TO CTLR BFR
WXFER:	CLRBIT	F@RDOP		;CLEAR READ OPER FLAG
	CALL	GETDMA		;GET DMA ADR, SET FOR WRITE
	CALL	BFROUT		;MOVE DATA TO THE BFR
	SETBIT	F@WIP		;SET WRITE-IN-PROGRESS FLAG
	LDA	ERFLG		;ERROR FLAG
	RET
;
;   NORMAL WRITE
;
WNORM:	LDA	U@CNT		;UNALC RECORD COUNT
	ORA	A
	JZ	WALC		;JIF DO ALLOC WRITE
	LXI	H,U@TRK
	CALL	DSKCMP		;UNALC DSK/TRK = REQ DSK/TRK ?
	JNZ	WALC		;NO, DO ALLOC WRITE
	LDA	R@SEC
	CMP	M		;UNALC SECT = REQ SECT ?
	JNZ	WALC		;NO, DO ALLOC WRITE
	CALL	BUMP		;BUMP UNALC PARMS FOR NEXT PASS
	CALL	TSTHST		;HOST = REQ ?
	JZ	WN1		;YES, CON'T TO FILL THE BFR
	TSTBIT	F@WIP		;WRITE IN PROGRESS ?
	CNZ	XWRT		;YES, WRITE OLD DATA ONTO DISK
	CALL	SETHST		;MAKE HOST = REQ
;
WN1:	TSTBIT	F@RDOP		;INTERVENING READ ?
	CNZ	XREAD		;YES, READ OLD UNALC DATA
	JMP	WXFER		;MOVE DATA TO BFR, EXIT
;
;   ALLOCATED WRITE
;
WALC:	XRA	A
	STA	U@CNT		;CLEAR UNALC RECORD COUNT
	CALL	TSTHST		;HOST = REQ ?
	JZ	WXFER		;YES -  MOVE DATA TO BFR, EXIT
	TSTBIT	F@WIP		;WRITE IN PROGRESS ?
	CNZ	XWRT		;YES, WRITE OLD DATA ONTO DISK
	CALL	SETHST		;MAKE HOST = REQ
	CALL	XREAD		;READ IN ALLOCATED DATA
	JMP	WXFER		;MOVE NEW DATA IN BFR, EXIT
;
;   DIRECTORY WRITE
;
WDIR:	XRA	A
	STA	U@CNT		;CLEAR UNALC RECORD COUNT
	CLRBIT	F@RDOP		;RESET 'RDOP' FLAG
	TSTBIT	F@WIP		;WRITE IN PROGRESS ?
	CNZ	XWRT		;YES, WRITE OLD DATA ONTO THE DISK
	CLRBIT	F@WIP		;CLEAR 'WIP' FLAG
	CALL	SETHST		;MAKE HOST = REQ
	CALL	XREAD		;READ DIR DATA
	RNZ			;RIF READ ERROR
	CALL	GETDMA		;GET DMA ADR, SET POINTERS
	CALL	BFROUT		;MOVE NEW DIR DATA INTO BFR
	JMP	XWRT		;WRITE DIR DATA, EXIT




;	---TEST HOST---
;
;   DETERMINES IF THE HOST DISK ADDRESS IS
;   THE SAME AS THE REQUESTED DISK ADDRESS.
;
;
TSTHST:	LXI	H,H@TRK
	CALL	DSKCMP		;TRACK & DRIVE THE SAME ?
	RNZ			;RIF NO
	LDA	RSA
	CMP	M		;SECTOR THE SAME ?
	RET			;IF A = 0 THEN THEY MATCH




;	---SET HOST---
;
;   SETS THE HOST DISK ADDRESS TO BE THE
;   SAME AS THE REQUESTED DISK ADDRESS.
;
;
SETHST:	LDA	R@DSK
	STA	H@DSK		;DRIVE #
	LHLD	R@TRK
	SHLD	H@TRK		;TRACK ADR
	LDA	RSA
	STA	H@SEC		;SECTOR ADR
	RET




;	---BUMP---
;
;   BUMPS PARAMETERS FOR UNALLOCATED WRITES.
;   PARMS ARE CHANGED FOR THE NEXT PASS THRU
;   THE CODE (NOT THE CURRENT PASS).
;
;
BUMP:	LXI	H,U@CNT		;UNALC RECORD COUNT
	DCR	M		;  DECR IT
	DCX	H		;H/L = U@SEC
	INR	M		;  INCR IT
	MOV	A,M
	CPI	CPMSPT		;CPM SECTORS PER TRACK
	RC			;RIF STAY ON SAME TRACK
; OVERFLOW TO NEXT TRACK
	MVI	M,0		;RESET SECTOR ADR
	LHLD	U@TRK
	INX	H		;INCR TRACK ADR
	SHLD	U@TRK
	RET




;	---GET DMA ADDRESS---
;
;   SETS THE CONTROLLER BUFFER ADDRESS TO THE CORRECT
;   STARTING POINT. ALSO SETS B=128 & H/L=DMADR.
;
;
GETDMA:	LHLD	DMADR		;DMA ADR
	IF	Z80
	MVI	C,CTDP		;FOR BLOCK I/O
	ENDIF
	MVI	B,128		;B = COUNT
	MVI	A,DBENB
	OUT	CTCSR		;ENB DATA BFR
	LDA	R@SEC		;REQUESTED SECTOR
	RRC
	MVI	A,0
	JNC	GET1		;JIF USE 1ST HALF OF BFR
	MOV	A,B		;   USE 2ND HALF OF BFR
GET1:	OUT	CTBFR		;SET CTLR DATA BFR ADR
	RET




;	---BUFFER INPUT---
;
;   READ 128 BYTES FROM THE CONTROLLER BUFFER
;
;
BFRIN	EQU	$
	IN	CTDP		;PRIME DATA INPUT
	NOP			;TIME DELAY
	IF	Z80		;IF USING A Z-80
	INIR			;BLOCK INPUT
	RET
	ELSE			;IF USING AN 8080
BFRIN1:	IN	CTDP		;GET DATA
	MOV	M,A		;PUT DATA INTO RAM
	INX	H
	DCR	B
	JNZ	BFRIN1
	RET
	ENDIF




;	---BUFFER OUTPUT---
;
;   OUTPUT 128 BYTES TO THE CONTROLLER BUFFER
;
;
BFROUT	EQU	$
	IF	Z80		;IF USING A Z-80
	OUTIR			;BLOCK OUTPUT
	RET
	ELSE			;IF USING AN 8080
	MOV	A,M		;GET DATA FROM RAM
	OUT	CTDP		;PUT DATA INTO BFR
	INX	H
	DCR	B
	JNZ	BFROUT
	RET
	ENDIF




;	---DISK ADDRESS COMPARE---
;
;   COMPARES EITHER THE HOST DISK ADDRESS OR THE UNALLOCATED
;   DISK ADDRESS AGAINST THE REQUESTED DISK ADDRESS.
;
;
DSKCMP:	LXI	D,R@TRK		;REQUESTED TRACK
	MVI	B,3
DC1:	LDAX	D
	CMP	M
	RNZ			;RIF ADRS NOT EQUAL
	INX	H
	INX	D
	DCR	B
	JNZ	DC1
	RET


	PAGE



;	======================================
;	** HARD DISK I/O & SUPPORT ROUTINES **
;	======================================




;	---READ A BLOCK---
;
;
XREAD:	LXI	H,RTBL		;READ CMD TBL
	CALL	DORW		;READ
;
XR1:	MVI	A,0
	RZ			;RIF READ/WRITE OK
	INR	A
	STA	ERFLG		;SET ERROR FLAG
	RET




;	---WRITE A BLOCK---
;
;
XWRT:	LXI	H,WTBL		;WRITE CMD TBL
	CALL	DORW		;WRITE A SECTOR
	JMP	XR1		;SET ERROR FLAG




;	---EXECUTE READ/WRITE COMMANDS---
;
;
DORW:	SHLD	CTA		;SAVE CMD TBL ADR
	CALL	XSEK		;SEEK TO NEW TRACK (IF REQUIRED)
	RNZ			;RIF SEEK FAILED
	CALL	XSEL		;HEAD SELECT
	LHLD	CTA		;GET CMD TBL ADR
;
DO0:	MOV	A,M
	STA	RETRY		;SET RETRY COUNT
	INX	H
	MOV	A,M
	OUT	CTCSR		;ENB CMP BFR
	INX	H
	MOV	A,M
	OUT	CTBFR		;SET CMP BFR ADR
	INX	H
	SHLD	CTA		;SAVE CMD TBL ADR
;
	LXI	H,RCA		;REAL CYL ADR
	MVI	B,3
DO1:	MOV	A,M
	OUT	CTDP		;PUT HDR INFO INTO CMP BFR
	INX	H
	DCR	B
	JNZ	DO1
	LDA	H@SEC
	OUT	CTDP		;SET SECT ADR FOR COMPARE
;
DO2:	CALL	XRDY		;DRIVE READY ?
	RNZ			;  RIF NO
	LHLD	CTA		;CMD TBL ADR
	MOV	A,M		;A = CNTL BANK
	INX	H
	MOV	B,A
	OUT	CTCSR		;SLCT CNTL BANK
	MOV	A,M
	OUT	CTBFR		;SET START ADR
	INX	H
	MOV	A,B
	ORI	START
	OUT	CTCSR		;START R/W CMD
;
DO3:	CALL	WFD		;WAIT FOR READ/WRITE TO FINISH
	RC			;ABORT, TIME-OUT ERROR
	ANA	M		;TEST CTLR STATUS (0=OK)
	MOV	B,A
	IN	DRCSR		;DRIVE STATUS
	ANI	WRTFLT
	CNZ	CLRDF		;CIF CLEAR DRIVE FAULT
	ORA	B		;SET/CLEAR ERROR FLAG (0=OK)
	RZ			;RIF READ/WRITE OK
	LXI	H,RETRY
	DCR	M		;DECR RETRY COUNT
	JNZ	DO2		;JIF RETRY READ/WRITE
	JMP	SEF		;SET ERROR FLAG, EXIT




;	---WAIT FOR DONE---
;
;
WFD:	PUSH	H		;SAVE H/L
	LXI	H,0		;TIME-OUT DELAY COUNT
;
WFD1:	IN	CTCSR		;CTLR STATUS
	RRC
	JC	WFD2		;JIF DONE
	DCX	H		;DECR DELAY COUNT
	MOV	A,H
	ORA	L
	JNZ	WFD1		;JIF CON'T WAITING
; TIME-OUT ERROR
	OUT	CTCSR		;STOP THE CTLR
	POP	H		;RESTORE H/L
	MVI	A,1
	ORA	A		;SET CPM ERROR FLAG
	STC			;SET INTERNAL ERROR FLAG
	RET
;
WFD2:	POP	H		;RESET H/L
	IN	CTCSR		;GET NON-CHANGING STATUS
	MOV	B,A	
	XRA	A
	OUT	CTCSR		;STOP CTLR
	MOV	A,B
	RET




;	---RESTORE---
;
;
	IF	FASTKZ		;FAST RESTORE ALGORITHM

XTKZ:	LXI	H,0
	SHLD	CHDT		;INIT CURR CYL ADR
	IN	DRCSR		;DRIVE STATUS
	ANI	TK00		;TRACK ZERO FLAG
	XRI	TK00		;..MAKE IT LOW-TRUE
	RZ			;RIF ALREADY AT TRACK ZERO
;
	CALL	XRDY		;DRIVE READY ?
	RNZ			;NO, ABORT
	MVI	A,MAXTKZ AND LMSK
	OUT	LOSC		;SET LSB OF SEEK COUNT
	MVI	A,MAXTKZ SHR 8
	OUT	HISC		;SET MSB
	MVI	A,SKOUT
	OUT	EXTCMD		;SET SEEK DIRC = OUTWARD
	MVI	A,SKCMD
	OUT	DRCSR		;ISSUE SEEK CMD
	LXI	H,0
	MVI	B,10		;INIT RETRY COUNT
;
XTKZ1:	IN	DRCSR		;DRIVE STATUS
	ANI	TK00		;TRACK ZERO FLAG
	JNZ	XTKZ2		;JIF AT TRACK ZERO
	DCX	H		;DECR TIME-OUT
	MOV	A,H
	ORA	L
	JNZ	XTKZ1
	DCR	B
	JNZ	XTKZ1
	OUT	HISC
	OUT	LOSC		;ZERO SEEK COUNTER
	JMP	SEF		;SET ERROR FLAG, ABORT
;
XTKZ2:	XRA	A
	OUT	HISC
	OUT	LOSC		;ZERO SEEK COUNTER
	JMP	WSC		;WAIT FOR SEEK DONE, EXIT

	ENDIF



	IF	NOT FASTKZ	;NORMAL RESTORE ALGORITHM

XTKZ:	LXI	H,0
	SHLD	CHDT		;SET CURRENT TRACK = 0
	LXI	B,MAXTKZ	;SET FIND COUNT
;
XTKZ1:	CALL	XRDY		;DRIVE READY ?
	RNZ			;   RIF NO
	IN	DRCSR		;DRIVE STATUS
	ANI	TK00		;TRACK ZERO INDICATOR
	XRI	TK00		;  MAKE IT LO-TRUE
	RZ			;RIF AT TRACK ZERO
	DCX	B		;DECR FIND COUNT
	MOV	A,B
	ORA	C
	JZ	SEF		;JIF REZERO FAILED
	XRA	A
	OUT	HISC
	INR	A
	OUT	LOSC		;SET SEEK COUNT = 1
	OUT	EXTCMD		;SET SEEK DIRECTION = OUT
	MVI	A,SKCMD
	OUT	DRCSR		;START SEEK
	CALL	WSC		;WAIT FOR SEEK DONE
	JNC	XTKZ1		;JIF SEEK COMPLETED
	RET			;ABORT, TIME-OUT ERROR

	ENDIF




;	---SEEK TO TRACK ZERO---
;
;
XSTZ:	TSTBIT	F@WIP
	JNZ	XSTZ1		;JIF WRITE IN PROGRESS
	STA	FLAGS		;MAKE HOST INACTIVE
XSTZ1:	LXI	H,0
	SHLD	R@TRK		;SET TK ADR = 0
	XRA	A		;SET FLAG = NO ERRORS
	RET




;	---SEEK---
;
;
XSEK:	MVI	A,3
	STA	RETRY		;SET RETRY COUNT
;
XSEK1:	CALL	XRDY		;DRIVE READY ?
	RNZ			;   RIF NO
	LHLD	H@TRK		;REQUESTED TRACK
	IF	NOT (DRSIZE AND 1)	;IF USING MS-1012 OR MS-4020
	MVI	B,2		;4 HEADS
	ELSE			;IF USING MS-1006 OR MS-4010
	MVI	B,1		;2 HEADS
	ENDIF
	CALL	DRS		;SHIFT H/L RIGHT 'N' TIMES
	LXI	D,MAXCYL	;# OF CYLS
	CALL	TSUB		;TEST REQUESTED CYL ADR
	RAL
	JNC	SEF		;JIF GOT INVALID CYL ADR
	IF	NOT (DRSIZE AND 1)	;IF USING MS-1012 OR MS-4020
	LDA	H@DSK		;HOST DISK
	ORA	A
	JZ	XSEK2		;JIF LOGICAL DRIVE ZERO
	LXI	D,MAXCYL
	DAD	D		;DRIVE ONE USES INNER HALF OF DISK
	ENDIF
XSEK2:	SHLD	RCA		;SAVE REAL CYL ADR
	XCHG
	LHLD	CHDT		;CURR TK ADR
	CALL	SUBT		; (OLD CYL ADR) - (NEW CYL ADR)
	RZ			;RIF AT REQUESTED CYL
	MVI	C,1		;SEEK DIRECTION = OUTWARD
	RAL
	JNC	XSEK3		;JIF SEEK OUTWARD
; SEEK INWARD
	MOV	A,L		;MAKE SEEK COUNT POSITIVE
	CMA			  ;
	MOV	L,A		  ;
	MOV	A,H		  ;
	CMA			  ;
	MOV	H,A		  ;
	INX	H		  ;
	MVI	C,3		;SET SEEK DIRECTION = INWARD
;
XSEK3:	MOV	A,L
	OUT	LOSC		;SET LSB OF SEEK COUNT
	MOV	A,H
	OUT	HISC		;SET MSB OF SEEK COUNT
	MOV	A,C
	OUT	EXTCMD		;SET DIRECTION OF SEEK
	MVI	A,SKCMD
	OUT	DRCSR		;INITIATE SEEK
	LHLD	RCA
	SHLD	CHDT		;UPDATE CURR CYL ADR
	CALL	WSC		;WAIT FOR SEEK DONE
	RC			;ABORT, TIME-OUT ERROR
; SEEK VERIFY
	MVI	A,3
	STA	VSRTC		;INIT RETRY COUNT
	MVI	A,CBENB
	OUT	CTCSR		;ENABLE BANK ZERO CMP BFR
	MVI	A,VCA
	OUT	CTBFR		;SET CMP BFR ADR
	LHLD	CHDT		;CURR CYL ADR
	MOV	A,L
	OUT	CTDP		;SET CYL ADR, LSB
	MOV	A,H
	OUT	CTDP		;SET CYL ADR, MSB
XSEK4:	MVI	A,VSA
	OUT	CTBFR		;SET M/CODE START ADR
	MVI	A,START
	OUT	CTCSR		;START VERIFY
	CALL	WFD		;WAIT FOR DONE
	RC			;ABORT, TIME-OUT ERROR
	ANI	0CH		;TEST CTLR STATUS
	RZ			;RIF VERIFY OK
	LXI	H,VSRTC
	DCR	M		;DECR RETRY COUNT
	JNZ	XSEK4		;JIF RETRY SEEK VERIFY
; VERIFY FAILED
	CALL	XTKZ		;RESTORE
	RNZ			;ABORT, REZERO FAILED
	LXI	H,RETRY
	DCR	M		;DECR RETRY COUNT
	JNZ	XSEK1		;JIF RETRY SEEK
	ORI	1		;SET FAIL FLAG
	RET			;ERROR EXIT





;	---WAIT FOR SEEK COMPLETE---
;
;
WSC:	PUSH	H		;SAVE REGS
	PUSH	B
	LXI	H,0		;TIME-OUT DELAY COUNT
	MVI	B,3		;..DITTO
;
WSC1:	IN	DRCSR		;DRIVE STATUS
	RAL
	JC	WSC2		;JIF SEEK DONE
	DCX	H		;DECR DELAY COUNT
	MOV	A,H
	ORA	L
	JNZ	WSC1		;JIF CON'T WAITING
	DCR	B
	JNZ	WSC1
; TIME-OUT ERROR
	POP	B		;RESTORE REGS
	POP	H
	MVI	A,1
	ORA	A		;SET CPM ERROR FLAG
	STC			;SET INTERNAL ERROR FLAG
	RET
;
WSC2:	POP	B		;RESTORE REGS
	POP	H
	IN	DRCSR		;DRIVE STATUS
	ANI	WRTFLT		;TEST FOR DRIVE FAULT
	RZ			;RIF OK
; A FAULT HERE NORMALLY INDICATES POWER SUPPLY PROBLEMS.
; FALL THRU TO 'CLRDF'.





;	---CLEAR DRIVE FAULT---
;
;
CLRDF:	XRA	A
	OUT	EXTCMD		;DE-SELECT THE DRIVE
				;  * FALL THRU TO 'XSEL' TO
				;    RE-SELECT THE DRIVE!





;	---HEAD SELECT---
;
;
XSEL:	LDA	H@TRK		;REQUESTED TRACK
	ANI	HEDMSK		;HEAD MASK
	STA	RHD		;SAVE REAL HEAD #
	ADD	A		;SHIFT HEAD # LEFT TWICE FOR H/W
	ADD	A
	ORI	1		;TO MAINTAIN DRIVE SLCT
	IF	DRSIZE LT 3	;IF USING MS-1006 OR MS-1012
	MOV	B,A
	LHLD	CHDT		;CURR CYL ADR
	LXI	D,HALF
	CALL	SUBT
	RAL
	MVI	A,0		;WE ALWAYS PRE-COMP!
	JC	XSEL1		;JIF 1ST HALF OF DISK
	MVI	A,LOWRT		;LOW WRITE CURRENT
XSEL1:	ORA	B		;B = HEAD SLCT INFO
	ENDIF
	OUT	EXTCMD		;SELECT HEAD 0...N
	RET




;	---DRIVE READY TEST---
;
;
XRDY:	IN	DRCSR		;DRIVE STATUS
	ANI	1		;DRIVE READY BIT
	XRI	1		;INVERT IT
	RET			;IF A = 0, DRIVE RDY





;	---COMMAND TABLES---
;
;
;   WRITE
;
WTBL:	DB	5		;RETRY COUNT
	DB	5		;CMP BFR ENB
	DB	0E6H		;CMP BFR ADR
	DB	BANK1		;CNTL BANK
	DB	0D3H		;START ADR
	DB	0EH		;STATUS MASK
;
;   READ
;
RTBL:	DB	10		;RETRY COUNT
	DB	4		;CMP BFR ENB
	DB	0EAH		;CMP BFR ADR
	DB	BANK0		;CNTL BANK
	DB	0D7H		;START ADDRESS
	DB	0EH		;STATUS MASK


	PAGE




;	==========================
;	** FLOPPY DISK ROUTINES **
;	==========================




;	---SELECT DISK---
;
;	     
FSEL:	LDA	R@DSK		;GET REQUESTED DISK
	SUI	MAXHD
	MOV	C,A		;SAVE IT IN C
	LXI	H,DISKNO	;GET OLD DRIVE
	MOV	A,M
	MOV	E,A		;PUT OLD DRIVE IN D&E
	MVI	D,0
	LXI	H,TRTAB 	;GET ADDRESS OF TRK TABLE
	PUSH	H		;SAVE IT
	DAD	D		;ADD DISK NO TO ADDRESS
	IN	TRACK		;RD 1793 TRACK ADDRESS
	MOV	M,A		;PUT INTO TABLE
	MOV	A,C		;GET REQUESTED DISK
	MOV	E,A		;PUT NEW DISK NO IN D&E
	POP	H		;RESTORE ADDRESS OF TRKTAB
	DAD	D		;ADD DISK NO TO ADDRESS
	MOV	A,M		;GET NEW TRK NO
	OUT	TRACK		;PUT IN 1793
	MOV	A,C		;UPDATE OLD DISK
	STA	DISKNO
	ADD	A		;PUT BIT 1&2 AT 4&5
	ADD	A
	ADD	A
	ADD	A
	STA	LATCH		;SAVE NEW LATCH CODE

DENSITY:LXI	H,DRVFLG       ;POINT TO DRV DENSITY FLAG
	MVI	B,0		;CLEAR B REG
	DAD	B		;INDEX INTO DRVFLG LOC
	MOV	A,M		;GET THE FLAG BYTE
	ORA	A		;LOGGED IN?
	JM	LOGED		;YES ITS LOGGED
	PUSH	H		;NO, SAVE FLAG ADDRESS
	LDA	LATCH		;GET LATCH CODE
	OUT	DCONT		;CHANGE LATCH OR DENSITY

;READ TRACK 0 SECTOR 1 FOR DENSITY BYTE AT 7E HEX.

	MVI    A,1		;SECTOR 1
			       ; STA	R@SEC		 ;SAVE SECTOR VALUE
	CALL   FHOME		;HOME THE DRIVE
	LHLD   DMADR		;GET CPM DMA ADDRESS
	PUSH   H		;SAVE IT ON STACK
	LXI    H,DBUFF		;POINT TO THE DMA BUFFER
	SHLD   DMADR		;SETUP READ DMA ADDRESS
	STA    ERCNT
	MVI    A,0D0H
	OUT    DCOM
	XTHL
	XTHL
	LHLD   DMADR
	MVI    A,1
	OUT    DSECT
	MVI    A,080H



;READ DATA USING THE READ ROUTINE

	CALL   READE  

;GET THE DENSITY BYTE AND DETERMINE DRIVE STATUS

	POP    H		  ;RESTORE DMA ADDRESS FROM STACK
	SHLD   DMADR		  ;STORE CP/M DMA ADDRESS
	POP    H		  ;RESTORE DENSITY FLAG ADDRESS
	LDA    DBUFF+7EH	  ;INDEX INTO DBUFF
	ORI    80H		  ;SET LOGGED IN BIT
	MOV    M,A		  ;PUT INTO FLAG BYTE
LOGED:	LXI    B,18		  ;INDEX VALU THROUGH DRIVE TABLE
	ANI    12H		  ;MASK DENSITY AND SIDE OUT
	ORA    A		  ;SINGLE DENSITY ?
	LXI    H,SDTAB		  ;POINT TO START OF TABLES
	JZ     DENSIT1		  ;YES, OVERLAY PARAM BLOCK

;CODE FOR DOUBLE SIDED DRIVE

	DAD	B		;NO ADD OFFSET TO NEXT TABLE
	CPI	2		;SINGLE DENSITY DOUBLE SIDED
	JZ	DENSIT1 	;YES
	DAD	B		;NO
	CPI	10H		;DOUBLE DENSITY SINGLE SIDED
	JZ	DENSIT1 	;YES



	DAD    B		  ;NO, MUST BE DOUB DEN/DOUB SIDE
DENSIT1:XCHG			  ;DRIVE TABLE POINTER --> D&E
	LDAX   D		  ;GET LOG AND DRIVE TYPE BYTE
	INX    D		  ;BUMP POINTER
	STA    DENS		  ;SET CURRENT DRIVE DENSITY
	PUSH   D		  ;SAVE DRIVE TABLE POINTER
	CALL   PARINDX		  ;COMPUTE PARM OVERLAY AREA
	POP    D		  ;RESTORE DRIVE TABLE POINTER
	LXI    B,0208H		  ;B=2,C=8 (COUNT VALUE)
MOVE:	LDAX   D		  ;GET XLAT BYTE
	MOV    M,A		  ;AND PUT IT INTO DW TABLE FOR DRIVE
	INX    D		  ;BUMP
	INX    H		  ;POINTERS
	DCR    B		  ;DEC COUNT
	JNZ    MOVE
	DAD    B		  ;NOW ADD INDEX INTO DPB0 AREA
	MOV    M,E		  ;GET LOW POINTER
	INX    H		  ;BUMP POINTER
	MOV    M,D		  ;GET HIGH POINTER

;
;  SELECT DRIVE AS A FUNCTION OF HL
;

PARINDX:LHLD   DISKNO		  ;LOAD DISK NO AND ZERO BYTE
	LXI    D,DPE0		  ;POINT TO DISK PARM START
	DAD    H		  ;*2
	DAD    H		  ;*4
	DAD    H		  ;*8
	DAD    H		  ;*16
	DAD    D		  ;COMPUTE INDEX FOR DRIVE
	XRA    A		  ;SET A = 0
	RET
;
;  MOVE DISK TO TRACK0
;

FHOME:	MVI   C,0		     ;SEEK TO TRACK 0
	MVI   A,0CH+STPRAT
	OUT   DCOM		     ;SEND SEEK TO 0
	IN    DWAIT
	MVI   A,0
	RET


;
; SET TRACK NUMBER TO = R@TRK AND SEEK TO TRACK
;
SETTRK: LDA  R@TRK		     ;GET TRACK NUMBER
	MOV  C,A		     ;SAVE IT IN C
	LHLD LATCH		     ;GET LATCH NEW AND OLD
	MOV  A,H		     ;LATCH VALUA TO A
	ANI  0B7H		     ;STRIP DENSITY AND SIDE BITS
	MOV  H,A		     ;RESTORE IT
	LDA  DENS		     ;CK IF DOUBLE SIDED
	RRC
	RRC			     ;LOOK AT BIT 1
	JNC  NOTSID		     ;IF BIT 1=0 ITS SINGLE SIDED
	MOV  A,C		     ;DOUBLE SIDED, GET TRACK NUMBER
	RRC			     ;DEVIDE BY 2
	MOV  B,A		     ;SAVE IN REG B
	MOV  A,L		     ;GET OLD LATCH VALUE
	JC   SIDE2		     ;CHANGE SIDE IF ODD TRACK
	ANI  0BFH		     ;CLEAR SIDE BIT FROM LATCH
	JMP  SETLAT
;
SIDE2:	ORI  40H		     ;TURN ON SIDE SELECT BIT
SETLAT: STA  CLATCH		     ;SAVE IT FOR LATER
	ANI  0BFH			;CLEAR SIDE BIT
	CALL OLDLAT			;CHECK FOR DRIVE CHANGE
	MOV  A,B			;RESTORE DUB SIDED TRACK #
	ANI  7FH			;CLEAR 7 BIT
	MOV  C,A			;TRK # NOW IN C REG
	JMP  TRKSET			;CK FOR DENSITY OF TRACK
	
OLDLAT: CMP  H				;NEW = OLD
	MVI  A,0FFH			;IF NOT SET FF
	JNZ  SFLAG
	CMA
SFLAG:	STA  HLSF			;SAVE HEAD LOAD SELECT FLAG
	RET

NOTSID: MOV  A,L			;GET LATCH VALUE
	STA  CLATCH			;SAVE IT
	CALL OLDLAT			;CK FOR DRIVE CHG

TRKSET:
	LDA DENS			;CK DRV DENSITY FLAG
	RRC				;IS BIT 0 = 0
	JNC  TRKSD			;YES WE ARE SINGLE DENSITY
	MOV  A,C			;NO RESTORE TRK #
	CPI  1				;IS IT TRK 1
	JC   TRKSD			;IF LESS THEN , SET SINGLE DENSITY
	LDA  CLATCH			;GET CURRENT LATCH VALUE
	ORI  8				;SET FOR DOUBLE DENSITY
	JMP  TRKDD			;

TRKSD:	LDA  CLATCH			;GET CURRENT LATCH VALUE
	ANI  0F7H			;TURN OFF BIT 4 (SINGLE DENSITY)
TRKDD:	STA  CLATCH			;SAVE NEW LATCH VALUE
	OUT  DCONT			;SELECT DISK AND MAKE DENSITY CHANGE
	MOV  A,C			;RESTORE TRK VALUE


;	MOVE HEAD TO TRK IN REG A

	
FSEEK:	PUSH B				;SAVE B&C
	MOV  B,A			;SAVE DEST. TRK
	MVI  A,RTCNT			;GET RETRY COUNT
SRETRY: STA  SERCNT			;STORE IN ERROR CNT
	IN   TRACK			;READ PRESENT TRACK #
	CMP  B				;SAME AS NEW TRK ?
	JNZ  NOTHR			;JIF NOT THERE
THERE:	POP  B				;RESTORE B&C
	RET
NOTHR:	MOV  A,B			;RESTORE A FROM B
	OUT  DDATA			;TRK TO DATA REG 1793
	MVI  A,14H+STPRAT+HLAB		;GET STEP RATE
	OUT  DCOM			;SEEK WITH VERIFY

	IN   DWAIT			;WAIT FOR STATUS
	IN   DSTAT
	ANI  91H			;CK STATUS
	JZ   THERE
	LDA  SERCNT			;GET ERROR CNT
	DCR  A				;DCR CNT
	JNZ  SRETRY			;RETRY SEEK
	POP  B				;RESTORE B&C
	PUSH B				;SAVE
	CALL RECOV			;IF SK RETRY = 10 CHECK
	POP  B
	MOV  A,C			;RECOVER TRK #
	JMP  FSEEK




;
;
;	 READ DATA FROM THE PRESENT TRK
;	USE STARTING ADDRESS AT DMAADR

FREAD:		  

	CALL	SETTRK

	

	MVI	A,RTCNT 	;GET RETRY COUNT
RRETRY:
	MVI	B,80H		;F/D READ CMD
	CALL	DSKSET		;SETUP 1793
	ORA	B		;OR IN RD
READE:	OUT	DCOM		;SEND CMD TO 1793
RLOOP:	IN	DWAIT		;WAIT FOR DRQ OR IRQ
	ORA	A		;CK FOR IRQ
	JP	RDONE
	IN	DDATA		;READ A BYTE OF DATA
	MOV	M,A		;PUT DATA IN MEM
	INX	H		;INC HL
	JMP	RLOOP		;GET NEXT BYTE
RDONE:	IN	DSTAT
	ANI	9DH		;CK STATUS
	RZ			;RETURN IF NO ERROR
	CALL	ERCHK		;CK FOR SEEK ERROR
	JNZ	RRETRY		;TRY READ AGIN
	CALL	RECOV		;CK FOR ABORT OR CONTINUE
	JMP	FREAD		;IF NOT CONTROL C TRY READ AGIN


RECOV:	
	IN	TRACK
	LXI	H,ERMSG 	;LOAD ERR MSG ADDRESS
	CALL	PRNT
	CALL	CI		;CONSOLE INPUT
	CPI	03H		;IS IT CRTL C
	RNZ
	JMP	WBOOT
;
;	ERCHK- CK FOR RECORD NOT FOUND
;
 
ERCHK:	ANI	10H		;IF RECORD NOT FOUND
	JNZ	CHKSK		;CK SEEK
	
CHKOK:	LDA	ERCNT		;GET RETRYS ALLOWED
	DCR	A		;DCR IT
	RET

CHKSK:	MVI	A,0C4H		;SEND CMD TO 1793
	OUT	DCOM		;TO READ ADDRESS
	IN	DWAIT
	IN	DDATA		;GET TH TRACK ADDRESS
	PUSH	PSW		;SAVE IT
	
CHKS2:	IN	DWAIT		;WAIT FOR IRQ
	ORA	A
	JP	CHKS3
	IN	DDATA		;READ ANOTHER BYTE OF TRK ADDRESS
	JMP	CHKS2
	
CHKS3:	IN	DSTAT		;READ 1793 STATUS
CHKS4:	POP	PSW		;UPDATE TRK REG
	OUT	TRACK
CHKS5:	LDA	R@TRK		;GET REQUIRED TRK#
	CALL	FSEEK
	JMP	CHKOK
DSKSET: STA	ERCNT
	MVI	A,0D0H		;CAUSE AN IRQ
	OUT	DCOM
	XTHL
	XTHL
	LHLD	DMADR		;GET STARTING ADDRESS
	LDA	R@SEC		;GET SECTOR #
	OUT	DSECT
	MVI	A,0				   
	RET

FWRT:		   
	CALL	SETTRK

	MVI	A,RTCNT 	;GET RETRY COUNT
WRETRY: 
	MVI	B,0A0H			;FLOPPY WRITE CMD
	CALL	DSKSET			;SET UP 1793
	ORA	B			;OR IN WRT CMD
WRITE2: OUT	DCOM
WLOOP:	IN	DWAIT			;WAIT FOR DRQ
	ORA	A			;SET FLAGS
	JP	WDONE			;JIF WRITE DONE
	MOV	A,M
	OUT	DDATA			;SEND WRT DATA TO 1793
	INX	H			;INC BYTE CNT
	JMP	WLOOP
	
WDONE:	IN	DSTAT			;READ 1793 STATUS
	ANI	0FDH
	RZ				;RETURN IF NO ERROR
	CALL	ERCHK
	JNZ	WRETRY
	CALL	RECOV
	JMP	FWRT 








