;
;   THIS TABLE DEFINES HARD DISK CONFIGURATION.
;
;	1. THE MS-1006 IS CONGIGURED AS A SINGLE 5 MEGABYTE DRIVE.
;	   THE MS-1012 IS CONFIGURED AS TWO LOGICAL 5 MEGABYTE DRIVES.
;	   THE MS-4010 IS CONFIGURED AS A SINGLE 7.8 MEGABYTE DRIVE.
;	   THE MS-4020 IS CONFIGURED AS TWO LOGICAL 7.8 MEGABYTE DRIVES.
;
;	2. THE CPM LOGICAL BLOCK SIZE IS 2048 BYTES (MS-1006/MS-1012)
;	   OR 4096 BYTES (MS-4010/MS-4020).
;
;	3. THERE ARE 1024 DIRECTORY ENTRIES PER LOGICAL DRIVE.
;
;	4. THE FIRST TWO TRACKS ARE RESERVED FOR THE SYSTEM. THIS WILL
;	   ALLOW AN AGGREGATE CCP/BDOS/CBIOS SIZE OF 16 K-BYTES.
;
;
;
