;
;
@BTST:	PUSH	H
	LXI	H,FLAGS		;BIT FLAGS
	ANA	M		;TEST THE BIT
	POP	H
	RET




;	---DOUBLE RIGHT SHIFT---
;
;   SHIFTS THE CONTENTS OF H/L RIGHT 'N' TIMES.
;
DRS:	PUSH	PSW		;SAVE 'A'
;
DRS1:	MOV	A,H		;MSB
	ORA	A		;CLEAR CY
	RAR
	MOV	H,A
	MOV	A,L		;LSB
	RAR
	MOV	L,A
	DCR	B		;B = SHIFT COUNT
	JNZ	DRS1
	POP	PSW		;RESTORE 'A'
	RET





;	---PRINT ROUTINE---
;
;
