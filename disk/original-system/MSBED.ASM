;
DIRBFR:	DS	128		;DIRECTORY BUFFER
;
	IF	DRSIZE EQ 1	;MS-1006
HALL0:	DS	306		;BIT MAP, DRIVE 0
	ENDIF
;
	IF	DRSIZE EQ 2	;MS-1012
HALL0:	DS	306		;BIT MAP, DRIVE 0
HALL1:	DS	306		;..DRIVE 1
	ENDIF
;
	IF	DRSIZE EQ 3	;MS-4010
HALL0:	DS	240		;BIT MAP, DRIVE 0
	ENDIF
;
	IF	DRSIZE EQ 4	;MS-4020
HALL0:	DS	240		;BIT MAP, DRIVE 0
HALL1:	DS	240		;..DRIVE 1
	ENDIF
