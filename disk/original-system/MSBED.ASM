	TITLE	'MSBED -- MINISCRIBE BACKEND DRIVER FOR CPM 2.2'

;	10-28-82




;   'MSBED' IS A HARD DISK ONLY BACKEND DRIVER FOR ANY CPM BASED
;   SYSTEM. THIS PROGRAM IS DESIGNED TO WORK WITH A MINISCRIBE
;   HARD DISK DRIVE (MS-1006, MS-1012, MS-4010, OR MS-4020). DRIVES
;   ARE CONFIGURED AS FOLLOWS:
;
;	MS-1006 = ONE 5 MEGABYTE DRIVE
;	MS-1012 = TWO 5 MEGABYTE DRIVES
;	MS-4010 = ONE 7.8 MEGABYTE DRIVE
;	MS-4020 = TWO 7.8 MEGABYTE DRIVES
;
;   READ THE FILE "BED.DOC" FOR INFORMATION REGARDING USAGE OF
;   THIS PROGRAM.






;	---PROGRAM CONFIGURATION---
;
;
;   THE FOLLOWING STATMENTS ARE USED TO CONFIGURE THE PROGRAM.
;
;	1. Z80 -- SET THIS "TRUE" IF YOU ARE USING A Z-80 MICROPROCESSOR.
;	   THIS WILL SPEED UP DATA TRANSFERS TO/FROM THE CONTROLLER
;	   BUFFER.
;
;	2. S100 -- SET THIS "TRUE" IF YOU ARE USING A CONTROLLER WITH
;	   AN S-100 BUS INTERFACE (STS). SET THIS "FALSE" IF YOU USING
;	   A CONTROLLER WITH A RIBBON CABLE INTERFACE (STR).
;
;	3. FASTKZ -- SET THIS 'TRUE' IF YOU ARE USING A MINISCRIBE HARD
;	   DISK DRIVE. SET THIS 'FALSE' IF YOU ARE NOT USING A MINISCRIBE
;	   DRIVE.
;
;		** WARNING -- SETTING 'FASTKZ' TO 'TRUE' FOR DRIVES
;			      OTHER THAN A MINISCRIBE MAY CAUSE SERIOUS
;			      MECHANICAL DRIVE FAILURES!
;
;
;	4. DRSIZE -- SET THIS TO A VALUE OF 1, 2, 3, OR 4 DEPENDING UPON
;	   THE TYPE OF DRIVE YOU ARE USING.
;
;		1 =  5 Megabyte MS-1006
;		2 = 10 Megabyte MS-1012
;		3 =  8 Megabyte MS-4010
;		4 = 20 Megabyte MS-4020
;
;
;
FALSE	EQU	0		;DEFINE FALSE
TRUE	EQU	NOT FALSE	;DEFINE TRUE
;
Z80	EQU	TRUE		;WE ARE USING A Z-80
;
S100	EQU	TRUE		;S-100 BUS (STS)
;
FASTKZ	EQU	TRUE		;FAST RESTORE
;
DRSIZE	EQU	4		;16 MEG MS-4020






;	---EQUATES---
;
;
STRT	EQU	62*1024		;PROGRAM START ADDRESS
WBOOT	EQU	0		;WARM BOOT
RPT	EQU	80H		;REPEAT
INDEX	EQU	10H		;INDEX BIT
VSA	EQU	8		;SEEK VERIFY START ADDRESS
VCA	EQU	1BH		;SEEK VERIFY COMPARE ADDRESS
LMSK	EQU	0FFH		;LSB MASK
;
	IF	DRSIZE EQ 1	;IF 5 MEG MS-1006
MAXHD	EQU	1		;NUMBER OF LOGICAL DISK DRIVES
MAXCYL	EQU	306		;NUMBER OF LOGICAL CYLINDERS/DRIVE
MAXTKZ	EQU	350		;RESTORE COUNT
HEDMSK	EQU	1		;HEAD MASK
	ENDIF
;
	IF	DRSIZE EQ 2	;IF 10 MEG MS-1012
MAXHD	EQU	2		;NUMBER OF LOGICAL DISK DRIVES
MAXCYL	EQU	306/2		;NUMBER OF LOGICAL CYLINDERS/DRIVE
MAXTKZ	EQU	350		;RESTORE COUNT
HEDMSK	EQU	3		;HEAD MASK
	ENDIF
;
	IF	DRSIZE EQ 3	;IF 8 MEG MS-4010
MAXHD	EQU	1		;NUMBER OF LOGICAL DISK DRIVES
MAXCYL	EQU	480		;NUMBER OF LOGICAL CYLINDERS/DRIVE
MAXTKZ	EQU	511		;RESTORE COUNT
HEDMSK	EQU	1		;HEAD MASK
	ENDIF
;
	IF	DRSIZE EQ 4	;IF 16 MEG MS-4020
MAXHD	EQU	2		;NUMBER OF LOGICAL DISK DRIVES
MAXCYL	EQU	480/2		;NUMBER OF LOGICAL CYLINDERS/DRIVE
MAXTKZ	EQU	511		;RESTORE COUNT
HEDMSK	EQU	3		;HEAD MASK
	ENDIF
;
MAXSEC	EQU	32		;NUMBER OF SECTORS PER TRACK
HALF	EQU	306/2		;HALF-WAY POINT
;
;   HARD DISK/CPM INTERFACE
;
	IF	DRSIZE LT 3	;IF USING MS-1006 OR MS-1012
BLKSIZ	EQU	2048		;NUMBER OF BYTES PER BLOCK
	ELSE			;IF USING MS-4010 OR MS-4020
BLKSIZ	EQU	4096		;NUMBER OF BYTES PER BLOCK
	ENDIF
CPMSPT	EQU	2*MAXSEC	;NUMBER OF CPM SECTORS PER TRACK
;
;   BIT FLAGS
;
F@RDOP	EQU	1		;READ OPERATION
F@RIP	EQU	2		;READ IN PROGRESS
F@WIP	EQU	4		;WRITE IN PROGRESS
;
;   DRIVE COMMANDS
;
SKOUT	EQU	1		;SEEK DIRECTION = OUTWARD
SKCMD	EQU	3		;SEEK
NOPC	EQU	40H		;NO PRE-COMPENSATION
LOWRT	EQU	80H		;LOW WRITE CURRENT
;
;   DRIVE STATUS
;
READY	EQU	1		;DRIVE READY
WRTFLT	EQU	2		;WRITE FAULT
TK00	EQU	4		;TRACK ZERO
RAWINDX	EQU	20H		;RAW INDEX
;
;   CONTROLLER COMMANDS
;
BANK0	EQU	0		;BANK 0 SELECT
BANK1	EQU	1		;BANK 1 SELECT
DBENB	EQU	2		;DATA BUFFER ENABLE
CBENB	EQU	4		;COMPARE BUFFER ENABLE
START	EQU	8		;START COMMAND
;
;   CONTROLLER STATUS
;
INDEX	EQU	10H		;DELAYED INDEX
SECTOR	EQU	20H		;SECTOR
;
;   DRIVE/CONTROLLER I/O
;
CBASE	EQU	60H		;BASE ADR OF THE CONTROLLER
	IF	S100	;IF S-100 BUS
DRCSR	EQU	CBASE		;DRIVE COMMAND/STATUS
EXTCMD	EQU	CBASE+1		;EXTENDED COMMNAND REGISTER
LOSC	EQU	CBASE+2		;SEEK COUNT, LSB
HISC	EQU	CBASE+3		;  * MSB
CTCSR	EQU	CBASE+4		;CONTROLLER COMMAND/STATUS
CTBFR	EQU	CBASE+5		;CONTROLLER BUFFER ADDRESS
CTDP	EQU	CBASE+6		;CONTROLLER DATA PORT
	ELSE		;IF RIBBON CABLE INTERFACE
DRCSR	EQU	CBASE+7		;DRIVE COMMAND/STATUS
EXTCMD	EQU	CBASE+6		;EXTENDED COMMNAND REGISTER
LOSC	EQU	CBASE+5		;SEEK COUNT, LSB
HISC	EQU	CBASE+4		;  * MSB
CTCSR	EQU	CBASE+3		;CONTROLLER COMMAND/STATUS
CTBFR	EQU	CBASE+2		;CONTROLLER BUFFER ADDRESS
CTDP	EQU	CBASE+1		;CONTROLLER DATA PORT
	ENDIF
;
;   ASCII CHARACTERS
;
CR	EQU	0DH		;CARRIAGE RETURN
LF	EQU	0AH		;LINE FEED

	PAGE


;	============
;	** MACROS **
;	============




;	---SET FLAG BIT---
;
;
SETBIT	MACRO	BIT
	MVI	A,BIT		;; A = BIT TO SET
	CALL	@BSET		;; SET THE BIT
	ENDM




;	---RESET FLAG BIT---
;
;
CLRBIT	MACRO	BIT
?Y	SET	NOT BIT
	MVI	A,?Y		;; A = CLEAR MASK
	CALL	@BRES		;; RESET THE BIT
	ENDM




;	---TEST A FLAG BIT---
;
;
TSTBIT	MACRO	BIT
	MVI	A,BIT		;; A = BIT UNDER TEST
	CALL	@BTST		;; TEST THE BIT
	ENDM




;	---Z80 BLOCK INPUT---
;
;
INIR	MACRO
	DB	0EDH,0B2H
	ENDM




;	---Z80 BLOCK OUTPUT---
;
;
OUTIR	MACRO
	DB	0EDH,0B3H
	ENDM

	PAGE

	ORG	STRT


;	============================
;	** ENTRY POINT JUMP TABLE **
;	============================
;
;
	JMP	BOOT		;  0 - COLD BOOT
DLA:	JMP	HOME		;  1 - TRACK ZERO SEEK
	JMP	SETDR		;  2 - SET DRIVE #
	JMP	SETTK		;  3 - SET TRACK ADR
	JMP	SETSEC		;  4 - SET SECTOR ADR
	JMP	SETDMA		;  5 - SET BUFFER ADDRESS
	JMP	READ		;  6 - READ A SECTOR
	JMP	WRITE		;  7 - WRITE A SECTOR
LOT:	JMP	$		;  8 - LIST OUTPUT READY TEST
	JMP	SXR		;  9 - SECTOR XLATE ROUTINE
;
;   SIGN-ON MESSAGE
;
HELLO:	DB	CR,LF,LF
	DB	'MSBED -- Vers 1.2',CR,LF
	DB	'28-Oct-82',CR,LF,'$'

	PAGE



;	======================
;	** DISK DEFINITIONS **
;	======================






;	---DISK PARAMETERS---
;
;
DPHDR:	DW	0,0		;HARD DISK, LOGICAL DRIVE 0
	DW	0,0
	DW	DIRBFR,HDBLK
	DW	LAST,HALL0
;
	IF	NOT (DRSIZE AND 1)	;IF USING MS-1012 OR MS-4020
	DW	0,0		;HARD DISK, LOGICAL DRIVE 1
	DW	0,0
	DW	DIRBFR,HDBLK
	DW	LAST,HALL1
	ENDIF






;	---HARD DISK PARAMETER BLOCK---
;
;
;   THIS TABLE DEFINES HARD DISK CONFIGURATION.
;
;	1. THE MS-1006 IS CONGIGURED AS A SINGLE 5 MEGABYTE DRIVE.
;	   THE MS-1012 IS CONFIGURED AS TWO LOGICAL 5 MEGABYTE DRIVES.
;	   THE MS-4010 IS CONFIGURED AS A SINGLE 7.8 MEGABYTE DRIVE.
;	   THE MS-4020 IS CONFIGURED AS TWO LOGICAL 7.8 MEGABYTE DRIVES.
;
;	2. THE CPM LOGICAL BLOCK SIZE IS 2048 BYTES (MS-1006/MS-1012)
;	   OR 4096 BYTES (MS-4010/MS-4020).
;
;	3. THERE ARE 1024 DIRECTORY ENTRIES PER LOGICAL DRIVE.
;
;	4. THE FIRST TWO TRACKS ARE RESERVED FOR THE SYSTEM. THIS WILL
;	   ALLOW AN AGGREGATE CCP/BDOS/CBIOS SIZE OF 16 K-BYTES.
;
;
;
HDBLK	EQU	$
;
	IF	DRSIZE LT 3	;IF USING MS-1006 OR MS-1012
	DW	2*MAXSEC	;SPT: SECTORS PER TRACK
	DB	4		;BSH: BLOCK SHIFT FACTOR
	DB	15		;BLM: BLOCK MASK
	DB	0		;EXM: NULL MASK
	DW	2439		;DSM: (DISK SIZE) - 1
	DW	1023		;DRM: (DIR SIZE) - 1
	DB	0FFH		;AL0: DIRECTORY ALLOCATION BITS, MSB
	DB	0FFH		;AL1:   * LSB
	DW	0		;CKS: CHECK SIZE
	DW	2		;OFF: TRACK OFFSET
	ENDIF
;
	IF	DRSIZE GT 2	;IF USING MS-4010 OR MS-4020
	DW	2*MAXSEC	;SPT: SECTORS PER TRACK
	DB	5		;BSH: BLOCK SHIFT FACTOR
	DB	31		;BLM: BLOCK MASK
	DB	0		;EXM: NULL MASK
	DW	1915		;DSM: (DISK SIZE) - 1
	DW	1023		;DRM: (DIR SIZE) - 1
	DB	0FFH		;AL0: DIRECTORY ALLOCATION BITS, MSB
	DB	0		;AL1:   * LSB
	DW	0		;CKS: CHECK SIZE
	DW	2		;OFF: TRACK OFFSET
	ENDIF

	PAGE

;	=====================
;	** CBIOS FUNCTIONS **
;	=====================




;	---COLD BOOT---
;
;
BOOT:	STA	FAD		;1ST AVAIL DRIVE NR
	LHLD	1		;WARM BOOT LINK ADR
	LXI	D,7*3
	DAD	D		;CALC ADR OF CBIOS F/D LINKS
	PUSH	H		;  SAVE IT
	LXI	D,X@TKZ
	CALL	MLNK		;GET/SAVE LINKS TO F/D DRIVER
	LHLD	X@LOT+1		;GET ADR OF LIST OUT TEST
	SHLD	LOT+1		;UPDATE MY OWN POINTER
	LXI	H,DLA		;DRIVER LINKS ADRS
	POP	D		;D/E = CBIOS F/D LINK ADRS
	CALL	MLNK		;OVERLAY CBIOS LINKS
; INITIALIZE STORAGE
	LXI	H,FLAGS		;START OF VARIABLES
	MVI	B,FLGSIZ	;NR OF VARIABLES
	XRA	A
BT1:	MOV	M,A
	INX	H
	DCR	B
	JNZ	BT1
	JMP	WBOOT		;EXIT, WARM BOOT SYSTEM




;	---SECTOR TRANSLATE ROUTINE---
;
;
SXR:	CALL	DRTST		;DRIVE TEST
	JC	X@SXR		;JIF DO F/D XLATE
	XCHG			;H/L = ADR OF XLATE TABLE
	MOV	A,L
	ORA	H		;TEST TABLE ADR
	JNZ	SXR1		;JIF DO XLATE
	DAD	B		;DON'T XLATE -- USE SECT ADR AS IS
	RET
;
SXR1:	DAD	B		;INDEX INTO THE TABLE
	MOV	L,M		;L = XLATED SECTOR ADR
	MVI	H,0		;H = 0 FOR 16-BIT VALUE
	RET




;	---HOME---
;
;
HOME:	CALL	DRTST		;DRIVE TEST
	JC	X@TKZ		;JIF DO F/D HOME
	CPI	MAXHD
	JNC	SEF		;JIF INVALID DRIVE #
	LXI	H,DOTKZ
	MOV	A,M		;GET FORCE TKZ FLAG
	MVI	M,1		;SET FLAG FOR NEXT TIME
	ORA	A
	JNZ	XSTZ		;JIF SEEK TO ZERO
	LXI	H,0
	SHLD	R@TRK		;SET REQ TRACK = ZERO
	JMP	XTKZ		;DO TKZ 1ST TIME
;
;   SET ERROR FLAG
;
SEF:	MVI	A,1		;A = ERROR CODE
	ORA	A		;SET 8080/Z80 FLAGS
	RET




;	---READ---
;
;
READ:	CALL	DRTST		;DRIVE TEST
	JC	X@RD		;JIF DO F/D READ
	CPI	MAXHD
	JNC	SEF		;JIF INVALID DRIVE NR
	JMP	HDREAD		;READ FROM H/D




;	---WRITE---
;
;
WRITE:	CALL	DRTST		;DRIVE TEST
	JC	X@WRT		;JIF DO F/D WRITE
	CPI	MAXHD
	JNC	SEF		;JIF INVALID DRIVE NR
	JMP	HDWRT		;WRITE TO H/D




;	---SET DRIVE NUMBER---
;
;
SETDR:	MOV	A,C		;A = NEW DRIVE #
	STA	R@DSK		;..SAVE IT
	CALL	DRTST		;DRIVE TEST
	JC	X@SEL		;DO F/D SLCT
	LXI	H,0
	CPI	MAXHD
	RNC			;RIF INVALID DRIVE #
	MOV	L,A
	DAD	H		;SHIFT H/L LEFT 4
	DAD	H		;   (HL = HL*16)
	DAD	H
	DAD	H
	LXI	D,DPHDR		;DISK PARM HDR
	DAD	D		;H/L = DPHDR FOR SELECTED DRIVE
	RET




;	---SET SECTOR ADR---
;
;
SETSEC:	MOV	A,C
	STA	R@SEC		;SAVE SECTOR ADR
; SET REAL SECTOR ADR FOR THE H/D DRIVER
	ANI	NOT 1		;CLEAR LOW ORDER BIT
	RRC			;THERE ARE 2 CPM SECTORS PER H/D SECT
	STA	RSA		;SAVE REAL SECTOR ADR
	JMP	X@SEC		;PASS INFO TO F/D DRIVER, EXIT





;	---SET TRACK ADDRESS---
;
;
SETTK:	CALL	DRTST		;DRIVE TEST
	JC	X@TK		;JIF F/D
	MOV	H,B
	MOV	L,C
	SHLD	R@TRK		;SAVE TRACK ADR
	RET




;	---SET DMA ADDRESS---
;
;
SETDMA:	MOV	H,B
	MOV	L,C
	SHLD	DMADR		;SAVE DMA ADR
	JMP	X@DMA		;PASS INFO TO F/D DRIVER, EXIT


	PAGE


;	======================================
;	** HARD DISK BLOCK/DEBLOCK ROUTINES **
;	======================================




;	---HARD DISK READ---
;
;
HDREAD:	XRA	A
	STA	ERFLG		;CLEAR THE ERROR FLAG
	SETBIT	F@RDOP		;SET READ OPERATION FLAG
	TSTBIT	F@WIP		;WRITE IN PROGRESS ?
	CNZ	XWRT		;YES, WRITE DATA BEFORE READ
	CLRBIT	F@WIP		;RESET 'WIP' FLAG
	CALL	TSTHST		;HOST = REQ ?
	JNZ	HDRD1		;NO, READ A BLOCK
	TSTBIT	F@RIP		;PRIOR BLOCK READ ?
	JNZ	HDRD2		;YES, JUST EXTRACT DATA FROM BFR
HDRD1:	CALL	SETHST		;MAKE HOST=REQ
	CALL	XREAD		;READ A BLOCK
HDRD2:	CALL	GETDMA		;GET DMA ADR, SET POINTERS
	CALL	BFRIN		;MOVE DATA TO RAM
	SETBIT	F@RIP		;SET READ-IN-PROGRESS FLAG
	LDA	ERFLG		;ERROR FLAG
	RET




;	---HARD DISK WRITE---
;
;
HDWRT:	XRA	A
	STA	ERFLG		;CLEAR THE ERROR FLAG
	CLRBIT	F@RIP		;CLEAR READ-IN-PROGRESS FLAG
	MOV	A,C		;A = WRITE MODE
	DCR	A
	JZ	WDIR		;DO DIRECTORY WRITE
	JM	WNORM		;DO NORMAL WRITE
;
;   UNALLOCATED WRITE
;
WUN:	TSTBIT	F@WIP		;WRITE IN PROGRESS ?
	CNZ	XWRT		;YES, WRITE DATA IN BFR
; SET UNALLOC RECORD PARAMETERS
	MVI	A,BLKSIZ/128
	STA	U@CNT		;SET UNALLOC RECORD COUNT
	CALL	DRTST		;GET REQ DRIVE
	STA	U@DSK		;UPDATE DRIVE NUM
	LDA	R@SEC
	STA	U@SEC		;UPDATE SECTOR ADR
	LHLD	R@DSK
	SHLD	U@DSK		;UPDATE DRIVE & SECTOR
	LHLD	R@TRK
	SHLD	U@TRK		;UPDATE TRACK ADR
	CALL	SETHST		;SET HOST = REQ
	CALL	BUMP		;BUMP UNALC PARMS FOR NEXT PASS

; XFER DATA TO CTLR BFR
WXFER:	CLRBIT	F@RDOP		;CLEAR READ OPER FLAG
	CALL	GETDMA		;GET DMA ADR, SET FOR WRITE
	CALL	BFROUT		;MOVE DATA TO THE BFR
	SETBIT	F@WIP		;SET WRITE-IN-PROGRESS FLAG
	LDA	ERFLG		;ERROR FLAG
	RET
;
;   NORMAL WRITE
;
WNORM:	LDA	U@CNT		;UNALC RECORD COUNT
	ORA	A
	JZ	WALC		;JIF DO ALLOC WRITE
	LXI	H,U@TRK
	CALL	DSKCMP		;UNALC DSK/TRK = REQ DSK/TRK ?
	JNZ	WALC		;NO, DO ALLOC WRITE
	LDA	R@SEC
	CMP	M		;UNALC SECT = REQ SECT ?
	JNZ	WALC		;NO, DO ALLOC WRITE
	CALL	BUMP		;BUMP UNALC PARMS FOR NEXT PASS
	CALL	TSTHST		;HOST = REQ ?
	JZ	WN1		;YES, CON'T TO FILL THE BFR
	TSTBIT	F@WIP		;WRITE IN PROGRESS ?
	CNZ	XWRT		;YES, WRITE OLD DATA ONTO DISK
	CALL	SETHST		;MAKE HOST = REQ
;
WN1:	TSTBIT	F@RDOP		;INTERVENING READ ?
	CNZ	XREAD		;YES, READ OLD UNALC DATA
	JMP	WXFER		;MOVE DATA TO BFR, EXIT
;
;   ALLOCATED WRITE
;
WALC:	XRA	A
	STA	U@CNT		;CLEAR UNALC RECORD COUNT
	CALL	TSTHST		;HOST = REQ ?
	JZ	WXFER		;YES -  MOVE DATA TO BFR, EXIT
	TSTBIT	F@WIP		;WRITE IN PROGRESS ?
	CNZ	XWRT		;YES, WRITE OLD DATA ONTO DISK
	CALL	SETHST		;MAKE HOST = REQ
	CALL	XREAD		;READ IN ALLOCATED DATA
	JMP	WXFER		;MOVE NEW DATA IN BFR, EXIT
;
;   DIRECTORY WRITE
;
WDIR:	XRA	A
	STA	U@CNT		;CLEAR UNALC RECORD COUNT
	CLRBIT	F@RDOP		;RESET 'RDOP' FLAG
	TSTBIT	F@WIP		;WRITE IN PROGRESS ?
	CNZ	XWRT		;YES, WRITE OLD DATA ONTO THE DISK
	CLRBIT	F@WIP		;CLEAR 'WIP' FLAG
	CALL	SETHST		;MAKE HOST = REQ
	CALL	XREAD		;READ DIR DATA
	RNZ			;RIF READ ERROR
	CALL	GETDMA		;GET DMA ADR, SET POINTERS
	CALL	BFROUT		;MOVE NEW DIR DATA INTO BFR
	JMP	XWRT		;WRITE DIR DATA, EXIT




;	---TEST HOST---
;
;   DETERMINES IF THE HOST DISK ADDRESS IS
;   THE SAME AS THE REQUESTED DISK ADDRESS.
;
;
TSTHST:	LXI	H,H@TRK
	CALL	DSKCMP		;TRACK & DRIVE THE SAME ?
	RNZ			;RIF NO
	LDA	RSA
	CMP	M		;SECTOR THE SAME ?
	RET			;IF A = 0 THEN THEY MATCH




;	---SET HOST---
;
;   SETS THE HOST DISK ADDRESS TO BE THE
;   SAME AS THE REQUESTED DISK ADDRESS.
;
;
SETHST:	LDA	R@DSK
	STA	H@DSK		;DRIVE #
	LHLD	R@TRK
	SHLD	H@TRK		;TRACK ADR
	LDA	RSA
	STA	H@SEC		;SECTOR ADR
	RET




;	---BUMP---
;
;   BUMPS PARAMETERS FOR UNALLOCATED WRITES.
;   PARMS ARE CHANGED FOR THE NEXT PASS THRU
;   THE CODE (NOT THE CURRENT PASS).
;
;
BUMP:	LXI	H,U@CNT		;UNALC RECORD COUNT
	DCR	M		;  DECR IT
	DCX	H		;H/L = U@SEC
	INR	M		;  INCR IT
	MOV	A,M
	CPI	CPMSPT		;CPM SECTORS PER TRACK
	RC			;RIF STAY ON SAME TRACK
; OVERFLOW TO NEXT TRACK
	MVI	M,0		;RESET SECTOR ADR
	LHLD	U@TRK
	INX	H		;INCR TRACK ADR
	SHLD	U@TRK
	RET




;	---GET DMA ADDRESS---
;
;   SETS THE CONTROLLER BUFFER ADDRESS TO THE CORRECT
;   STARTING POINT. ALSO SETS B=128 & H/L=DMADR.
;
;
GETDMA:	LHLD	DMADR		;DMA ADR
	IF	Z80
	MVI	C,CTDP		;FOR BLOCK I/O
	ENDIF
	MVI	B,128		;B = COUNT
	MVI	A,DBENB
	OUT	CTCSR		;ENB DATA BFR
	LDA	R@SEC		;REQUESTED SECTOR
	RRC
	MVI	A,0
	JNC	GET1		;JIF USE 1ST HALF OF BFR
	MOV	A,B		;   USE 2ND HALF OF BFR
GET1:	OUT	CTBFR		;SET CTLR DATA BFR ADR
	RET




;	---BUFFER INPUT---
;
;   READ 128 BYTES FROM THE CONTROLLER BUFFER
;
;
BFRIN	EQU	$
	IN	CTDP		;PRIME DATA INPUT
	NOP			;TIME DELAY
	IF	Z80		;IF USING A Z-80
	INIR			;BLOCK INPUT
	RET
	ELSE			;IF USING AN 8080
BFRIN1:	IN	CTDP		;GET DATA
	MOV	M,A		;PUT DATA INTO RAM
	INX	H
	DCR	B
	JNZ	BFRIN1
	RET
	ENDIF




;	---BUFFER OUTPUT---
;
;   OUTPUT 128 BYTES TO THE CONTROLLER BUFFER
;
;
BFROUT	EQU	$
	IF	Z80		;IF USING A Z-80
	OUTIR			;BLOCK OUTPUT
	RET
	ELSE			;IF USING AN 8080
	MOV	A,M		;GET DATA FROM RAM
	OUT	CTDP		;PUT DATA INTO BFR
	INX	H
	DCR	B
	JNZ	BFROUT
	RET
	ENDIF


	PAGE



;	======================================
;	** HARD DISK I/O & SUPPORT ROUTINES **
;	======================================




;	---READ A BLOCK---
;
;
XREAD:	LXI	H,RTBL		;READ CMD TBL
	CALL	DORW		;READ
;
XR1:	MVI	A,0
	RZ			;RIF READ/WRITE OK
	INR	A
	STA	ERFLG		;SET ERROR FLAG
	RET




;	---WRITE A BLOCK---
;
;
XWRT:	LXI	H,WTBL		;WRITE CMD TBL
	CALL	DORW		;WRITE A SECTOR
	JMP	XR1		;SET ERROR FLAG




;	---EXECUTE READ/WRITE COMMANDS---
;
;
DORW:	SHLD	CTA		;SAVE CMD TBL ADR
	CALL	XSEK		;SEEK TO NEW TRACK (IF REQUIRED)
	RNZ			;RIF SEEK FAILED
	CALL	XSEL		;HEAD SELECT
	LHLD	CTA		;GET CMD TBL ADR
;
DO0:	MOV	A,M
	STA	RETRY		;SET RETRY COUNT
	INX	H
	MOV	A,M
	OUT	CTCSR		;ENB CMP BFR
	INX	H
	MOV	A,M
	OUT	CTBFR		;SET CMP BFR ADR
	INX	H
	SHLD	CTA		;SAVE CMD TBL ADR
;
	LXI	H,RCA		;REAL CYL ADR
	MVI	B,3
DO1:	MOV	A,M
	OUT	CTDP		;PUT HDR INFO INTO CMP BFR
	INX	H
	DCR	B
	JNZ	DO1
	LDA	H@SEC
	OUT	CTDP		;SET SECT ADR FOR COMPARE
;
DO2:	CALL	XRDY		;DRIVE READY ?
	RNZ			;  RIF NO
	LHLD	CTA		;CMD TBL ADR
	MOV	A,M		;A = CNTL BANK
	INX	H
	MOV	B,A
	OUT	CTCSR		;SLCT CNTL BANK
	MOV	A,M
	OUT	CTBFR		;SET START ADR
	INX	H
	MOV	A,B
	ORI	START
	OUT	CTCSR		;START R/W CMD
;
DO3:	CALL	WFD		;WAIT FOR READ/WRITE TO FINISH
	RC			;ABORT, TIME-OUT ERROR
	ANA	M		;TEST CTLR STATUS (0=OK)
	MOV	B,A
	IN	DRCSR		;DRIVE STATUS
	ANI	WRTFLT
	CNZ	CLRDF		;CIF CLEAR DRIVE FAULT
	ORA	B		;SET/CLEAR ERROR FLAG (0=OK)
	RZ			;RIF READ/WRITE OK
	LXI	H,RETRY
	DCR	M		;DECR RETRY COUNT
	JNZ	DO2		;JIF RETRY READ/WRITE
	JMP	SEF		;SET ERROR FLAG,EXIT




;	---WAIT FOR DONE---
;
;
WFD:	PUSH	H		;SAVE H/L
	LXI	H,0		;DELAY COUNT
;
WFD1:	IN	CTCSR		;CTLR STATUS
	RRC
	JC	WFD2		;JIF DONE
	DCX	H		;DECR DELAY COUNT
	MOV	A,H
	ORA	L
	JNZ	WFD1		;JIF CON'T WAITING
; TIME-OUT ERROR
	OUT	CTCSR		;STOP CTLR
	POP	H		;RESTORE H/L
	MVI	A,1
	ORA	A		;SET CPM ERROR FLAG
	STC			;SET INTERNAL ERROR FLAG
	RET
;
WFD2:	POP	H		;RESTORE H/L
	IN	CTCSR		;GET CTLR STATUS
	MOV	B,A	
	XRA	A
	OUT	CTCSR		;STOP CTLR
	MOV	A,B
	ORA	A		;CLEAR CY
	RET




;	---RESTORE---
;
;

	IF	FASTKZ		;IF USE FAST RESTORE ALGORITHM

XTKZ:	LXI	H,0
	SHLD	CHDT		;SET CURR TRACK ADR = 0
	IN	DRCSR		;DRIVE STATUS
	ANI	TK00		;TRACK ZERO FLAG
	XRI	TK00		;..MAKE IT LOW-TRUE
	RZ			;RIF ALREADY AT TRACK ZERO
;
	CALL	XRDY		;DRIVE READY ?
	RNZ			;NO, ABORT
	MVI	A,MAXTKZ AND LMSK
	OUT	LOSC		;SET LSB OF SEEK COUNT
	MVI	A,MAXTKZ SHR 8
	OUT	HISC		;SET MSB
	MVI	A,SKOUT
	OUT	EXTCMD		;SET SEEK DIRC = OUTWARD
	MVI	A,SKCMD
	OUT	DRCSR		;ISSUE SEEK CMD
	LXI	H,0
	MVI	B,10		;INIT RETRY COUNT
;
XTKZ1:	IN	DRCSR		;DRIVE STATUS
	ANI	TK00		;TRACK ZERO FLAG
	JNZ	XTKZ2		;JIF AT TRACK ZERO
	DCX	H		;DECR TIME-OUT
	MOV	A,H
	ORA	L
	JNZ	XTKZ1
	DCR	B
	JNZ	XTKZ1
	OUT	HISC
	OUT	LOSC		;ZERO SEEK COUNTER
	INR	A		;SET ERROR FLAG
	RET			;ABORT
;
XTKZ2:	XRA	A
	OUT	HISC
	OUT	LOSC		;ZERO SEEK COUNTER
	JMP	WSC		;WAIT FOR SEEK DONE, EXIT

	ENDIF



	IF	NOT FASTKZ	;IF USING NORMAL RESTORE ALGORITHM

XTKZ:	LXI	H,0
	SHLD	CHDT		;SET CURRENT TRACK = 0
	LXI	B,MAXTKZ	;SET RETRY COUNT
;
XTKZ1:	CALL	XRDY		;DRIVE READY ?
	RNZ			;   RIF NO
	IN	DRCSR		;DRIVE STATUS
	ANI	TK00		;TRACK ZERO INDICATOR
	XRI	TK00		;  MAKE IT LO-TRUE
	RZ			;RIF AT TRACK ZERO
	DCX	B		;DECR RETRY CNT
	MOV	A,B
	ORA	C
	JZ	SEF		;JIF REZERO FAILED
	XRA	A
	OUT	HISC
	INR	A
	OUT	LOSC		;SET SEEK COUNT = 1
	OUT	EXTCMD		;SET SEEK DIRECTION = OUT
	MVI	A,SKCMD
	OUT	DRCSR		;START SEEK
	CALL	WSC		;WAIT FOR SEEK DONE
	JNC	XTKZ1		;JIF SEEK COMPLETED
	RET			;ABORT, TIME-OUT ERROR

	ENDIF




;	---SEEK TO TRACK ZERO---
;
;
XSTZ:	TSTBIT	F@WIP
	JNZ	XSTZ1		;JIF WRITE IN PROGRESS
	STA	FLAGS		;MAKE HOST INACTIVE
XSTZ1:	LXI	H,0
	SHLD	R@TRK		;SET TK ADR = 0
	XRA	A		;SET FLAG = NO ERRORS
	RET




;	---SEEK---
;
;
XSEK:	MVI	A,3
	STA	RETRY		;SET RETRY COUNT
;
XSEK1:	CALL	XRDY		;DRIVE READY ?
	RNZ			;   RIF NO
	LHLD	H@TRK		;REQUESTED TRACK
	IF	NOT (DRSIZE AND 1)	;IF USING MS-1012 OR MS-4020
	MVI	B,2		;4 HEADS
	ELSE			;IF USING MS-1006 OR MS-4010
	MVI	B,1		;2 HEADS
	ENDIF
	CALL	DRS		;SHIFT H/L RIGHT 'N' TIMES
	LXI	D,MAXCYL	;# OF CYLS
	CALL	TSUB		;TEST REQUESTED CYL ADR
	RAL
	JNC	SEF		;JIF GOT INVALID CYL ADR
	IF	NOT (DRSIZE AND 1)	;IF HAVE 2 LOGICAL DRIVES
	PUSH	H
	LXI	H,FAD
	LDA	H@DSK		;HOST DISK
	SUB	M		;ADJUST DRIVE #
	POP	H
	JZ	XSEK2		;JIF LOGICAL DRIVE ZERO
	LXI	D,MAXCYL
	DAD	D		;DRIVE ONE USES INNER HALF OF DISK
	ENDIF
XSEK2:	SHLD	RCA		;SAVE REAL CYL ADR
	XCHG
	LHLD	CHDT		;CURR TK ADR
	CALL	SUBT		; (OLD CYL ADR) - (NEW CYL ADR)
	RZ			;RIF AT REQUESTED CYL
	MVI	C,1		;SEEK DIRECTION = OUTWARD
	RAL
	JNC	XSEK3		;JIF SEEK OUTWARD
; SEEK INWARD
	MOV	A,L		;MAKE SEEK COUNT POSITIVE
	CMA			  ;
	MOV	L,A		  ;
	MOV	A,H		  ;
	CMA			  ;
	MOV	H,A		  ;
	INX	H		  ;
	MVI	C,3		;SET SEEK DIRECTION = INWARD
;
XSEK3:	MOV	A,L
	OUT	LOSC		;SET LSB OF SEEK COUNT
	MOV	A,H
	OUT	HISC		;SET MSB OF SEEK COUNT
	MOV	A,C
	OUT	EXTCMD		;SET DIRECTION OF SEEK
	MVI	A,SKCMD
	OUT	DRCSR		;INITIATE SEEK
	LHLD	RCA
	SHLD	CHDT		;UPDATE CURR CYL ADR
	CALL	WSC		;WAIT FOR SEEK DONE
	RC			;ABORT, TIME-OUT ERROR
; SEEK VERIFY
	MVI	A,3
	STA	VSRTC		;INIT RETRY COUNT
	MVI	A,CBENB
	OUT	CTCSR		;ENABLE BANK ZERO CMP BFR
	MVI	A,VCA
	OUT	CTBFR		;SET CMP BFR ADR
	LHLD	CHDT		;CURR CYL ADR
	MOV	A,L
	OUT	CTDP		;SET CYL ADR, LSB
	MOV	A,H
	OUT	CTDP		;SET CYL ADR, MSB
XSEK4:	MVI	A,VSA
	OUT	CTBFR		;SET M/CODE START ADR
	MVI	A,START
	OUT	CTCSR		;START VERIFY
	CALL	WFD		;WAIT FOR DONE
	RC			;ABORT, TIME-OUT ERROR
	ANI	0CH		;TEST CTLR STATUS
	RZ			;RIF VERIFY OK
	LXI	H,VSRTC
	DCR	M		;DECR RETRY COUNT
	JNZ	XSEK4		;JIF RETRY SEEK VERIFY
; VERIFY FAILED
	CALL	XTKZ		;RESTORE
	RNZ			;ABORT, REZERO FAILED
	LXI	H,RETRY
	DCR	M		;DECR RETRY COUNT
	JNZ	XSEK1		;JIF RETRY SEEK
	ORI	1		;SET FAIL FLAG
	RET			;ERROR EXIT





;	---WAIT FOR SEEK COMPLETE---
;
;
WSC:	PUSH	H		;SAVE REGS
	PUSH	B
	LXI	H,0		;TIME-OUT DELAY COUNT
	MVI	B,3		;..DITTO
;
WSC1:	IN	DRCSR		;DRIVE STATUS
	RAL
	JC	WSC2		;JIF SEEK DONE
	DCX	H		;DECR DELAY COUNT
	MOV	A,H
	ORA	L
	JNZ	WSC1		;JIF CON'T WAITING
	DCR	B
	JNZ	WSC1
; TIME-OUT ERROR
	POP	B		;RESTORE REGS
	POP	H
	MVI	A,1
	ORA	A		;SET CPM ERROR FLAG
	STC			;SET INTERNAL ERROR FLAG
	RET
;
WSC2:	POP	B		;RESTORE REGS
	POP	H
	IN	DRCSR		;DRIVE STATUS
	ANI	WRTFLT		;TEST FOR DRIVE FAULT
	RZ			;RIF OK
; A FAULT HERE NORMALLY INDICATES POWER SUPPLY PROBLEMS.
; FALL THRU TO 'CLRDF'.





;	---CLEAR DRIVE FAULT---
;
;
CLRDF:	XRA	A
	OUT	EXTCMD		;DE-SELECT THE DRIVE
				;  * FALL THRU TO 'XSEL' TO
				;    RE-SELECT THE DRIVE!





;	---HEAD SELECT---
;
;
XSEL:	LDA	H@TRK		;REQUESTED TRACK
	ANI	HEDMSK		;HEAD MASK
	STA	RHD		;SAVE REAL HEAD #
	ADD	A		;SHIFT HEAD # LEFT TWICE FOR H/W
	ADD	A
	ORI	1		;TO MAINTAIN DRIVE SLCT
	IF	DRSIZE LT 3	;IF USING MS-1006 OR MS-1012
	MOV	B,A
	LHLD	CHDT		;CURR CYL ADR
	LXI	D,HALF
	CALL	SUBT
	RAL
	MVI	A,0		;WE ALWAYS PRE-COMP!
	JC	XSEL1		;JIF 1ST HALF OF DISK
	MVI	A,LOWRT		;LOW WRITE CURRENT
XSEL1:	ORA	B		;B = HEAD SLCT INFO
	ENDIF
	OUT	EXTCMD		;SELECT HEAD 0...N
	RET




;	---DRIVE READY TEST---
;
;
XRDY:	IN	DRCSR		;DRIVE STATUS
	ANI	1		;DRIVE READY BIT
	XRI	1		;INVERT IT
	RET			;IF A = 0, DRIVE RDY





;	---COMMAND TABLES---
;
;
;   WRITE
;
WTBL:	DB	5		;RETRY COUNT
	DB	5		;CMP BFR ENB
	DB	0E6H		;CMP BFR ADR
	DB	BANK1		;CNTL BANK
	DB	0D3H		;START ADR
	DB	0EH		;STATUS MASK
;
;   READ
;
RTBL:	DB	10		;RETRY COUNT
	DB	4		;CMP BFR ENB
	DB	0EAH		;CMP BFR ADR
	DB	BANK0		;CNTL BANK
	DB	0D7H		;START ADDRESS
	DB	0EH		;STATUS MASK




;	---DISK ADDRESS COMPARE---
;
;   COMPARES EITHER THE HOST DISK ADDRESS OR THE UNALLOCATED
;   DISK ADDRESS AGAINST THE REQUESTED DISK ADDRESS.
;
;
DSKCMP:	LXI	D,R@TRK		;REQUESTED TRACK
	MVI	B,3
DC1:	LDAX	D
	CMP	M
	RNZ			;RIF ADRS NOT EQUAL
	INX	H
	INX	D
	DCR	B
	JNZ	DC1
	RET


