;
;
@BRES:	PUSH	H
	LXI	H,FLAGS		;BIT FLAGS
	ANA	M		;KILL UNWANTED BIT
	MOV	M,A
	POP	H
	RET




;	---TEST BIT FLAG---
;
;
@BTST:	PUSH	H
	LXI	H,FLAGS		;BIT FLAGS
	ANA	M		;TEST THE BIT
	POP	H
	RET




;	---DOUBLE RIGHT SHIFT---
;
;   SHIFTS THE CONTENTS OF H/L RIGHT 'N' TIMES.
;
DRS:	PUSH	PSW		;SAVE 'A'
;
DRS1:	MOV	A,H		;MSB
	ORA	A		;CLEAR CY
	RAR
	MOV	H,A
	MOV	A,L		;LSB
	RAR
	MOV	L,A
	DCR	B		;B = SHIFT COUNT
	JNZ	DRS1
	POP	PSW		;RESTORE 'A'
	RET




;	---MOVE LINKS---
;
;
MLNK:	MVI	B,9*3		;9 LINKS
;
ML1:	MOV	A,M		;GET
	STAX	D		;PUT
	INX	H
	INX	D
	DCR	B
	JNZ	ML1
	RET




;	---DRIVE TEST---
;
;
DRTST:	LXI	H,FAD		;1ST AVAIL DRIVE #
	LDA	R@DSK		;REQUSTED DISK
	SUB	M		;IF CY=1 THEN MUST BE F/D
	RET			;   OTHERWISE WILL BE H/D




;	---16 BIT SUBTRACTION---
;
;
SUBT:	MOV	A,L
	SUB	E		;LSB
	MOV	L,A
	MOV	A,H
	SBB	D		;MSB
	MOV	H,A
	ORA	L		;TEST FOR ZERO RESULTS
	MOV	A,H		;FOR EXTERNAL USE
	RET




;	---16 BIT COMPARISON TEST---
;
;
TSUB:	PUSH	H		;SAVE H/L
	CALL	SUBT		; (H/L) - (D/E)
	POP	H		;RESTORE H/L
	RET




