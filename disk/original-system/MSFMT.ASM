;	---CALL BDOS---
;
;
CPM	MACRO	FC
	CALL	SYSTEM		;; SYSTEM CALL ROUTINE
	DB	FC		;; CPM FUNCTION CODE
	ENDM




;	---PRINT MESSAGES---
;
;
PRNT	MACRO	MSG
	LXI	D,MSG		;; ADR OF THE MSG
	CPM	F@PRNT		;; PRINT THE MSG
	ENDM

	PAGE

	ORG	STRT	


;	==========================
;	** PROGRAM ENTRY POINT **
;	==========================
;
;
;
BGN:	LXI	SP,STACK	;USE INTERNAL STACK
	CALL	COFF		;STOP ANY PRIOR ACTIVITY
	PRNT	MSG1		;SAY HELLO
	MVI	A,1
	OUT	EXTCMD		;SLCT DRIVE ZERO
	INR	A
	OUT	DRCSR		;ENABLE INDEX/SECTOR TO DATA BOARD
	CALL	BST		;BUILD SECTOR TABLE
;
;   COMMAND LOOP
;
LOOP:	LXI	SP,STACK	;RESET SP
	PRNT	MSG2		;PRINT MENU
	LDA	BGNHED
	CALL	BTH1		;PRINT START HEAD
	MVI	E,'-'
	CPM	F@CO		;PRINT SEPERATOR
	LDA	ENDHED		;END HEAD NUM
	DCR	A		;..ADJUST IT
	CALL	BTH1		;..PRINT IT
	PRNT	MSG2A		; 'CYLS = '
	LHLD	BGNCYL
	CALL	P3D		;PRINT START CYL
	MVI	E,'-'
	CPM	F@CO		;PRINT SEPERATOR
	LHLD	ENDCYL
	DCX	H
	CALL	P3D		;PRINT END CYL ADR
	PRNT	MSG2B		; 'OPTION?'
;
	MVI	A,1
	CALL	RCB		;GET OPER CMD
	CPI	'C'
	JZ	NEWCYL		;JIF ALTER CYL LIMITS
	CPI	'H'
	JZ	NEWHED		;JIF GET NEW HEAD LIMITS
	CPI	'F'
	JZ	FORMAT		;JIF FORMAT A DISK
	CPI	'I'
	JZ	CLRDIR		;INITIALIZE DIRECTORY
	CPI	'X'
	JZ	XIT		;JIF EXIT TO CPM
;
;   INVALID INPUT
;
INV:	PRNT	MSG3		;PRINT 'INVALID INPUT'
	JMP	LOOP		;DO NEXT CMD
;
;   EXIT TO CPM
;
XIT:	CALL	CRLF		;DO CR.LF
	CALL	COFF		;TURN DRIVE/CTLR OFF
 	IF	TEST
	JMP	DEBUG		;IF WE ARE TESTING
 	ELSE
 	JMP	WBOOT		;WARM BOOT CPM
 	ENDIF




;	---GET NEW HEAD LIMITS---
;
;
NEWHED:	PRNT	MSG27		; 'START HEAD? '
	CALL	NHX		;GET HEAD NUM
	JNC	INV		;JIF INVALID HEAD NUM
	STA	TEMP		;SAVE NEW START HEAD
	PRNT	MSG28		; 'END HEAD? '
	CALL	NHX		;GET HEAD NUM
	JNC	INV		;JIF INVALID HEAD NUM
	INR	A		;FOR PROPER TESTING
	MOV	B,A		;B = END HEAD (+1)
	LDA	TEMP		;A = START HEAD
	CMP	B
	JNC	NH1		;JIF SH > EH
	MOV	L,A
	MOV	H,B
	SHLD	BGNHED		;SAVE NEW HEAD LIMITS
	JMP	LOOP		;DO NEXT CMD
; ERROR, START HEAD > END HEAD
NH1:	PRNT	MSG29		;PRINT ERROR MSG
	JMP	LOOP		;DO NEXT CMD
;
;   GET HEAD NUMBER
;
NHX:	MVI	A,2
	CALL	RCB		;INPUT HEAD NUM FROM OPER
	CALL	CONV		;CONVERT INPUT TO BINARY
	MOV	A,L
	CPI	MAXHD		;TEST HEAD NUM
	RET




;	---GET NEW CYLINDER LIMITS---
;
;
NEWCYL:	PRNT	MSG30		; 'START CYL? '
	CALL	NCX		;GET START CYL ADR
	JNC	INV		;JIF INVALID CYL ADR
	SHLD	TEMP		;SAVE CYL ADR
	PRNT	MSG31		; 'END CYL? '
	CALL	NCX		;GET END CYL ADR
	JNC	INV		;JIF INVALID CYL ADR
	INX	H		;FOR PROPER TESTING
	XCHG			;D/E = END CYL ADR
	LHLD	TEMP		;H/L = START CYL ADR
	CALL	TSUB		;TEST (H/L) - (D/E)
	JNC	NC1		;JIF SC > EC
	SHLD	BGNCYL		;SAVE NEW START CYL ADR
	XCHG
	SHLD	ENDCYL		;SAVE NEW END CYL ADR
	JMP	LOOP		;DO NEXT CMD
; ERROR, START CYL > END CYL
NC1:	PRNT	MSG32		;PRINT ERROR MSG
	JMP	LOOP		;DO NEXT CMD
;
;   GET CYLINDER ADDRESS
;
NCX:	MVI	A,4
	CALL	RCB		;GET CYL ADR FROM OPER
	CALL	CONV		;CONVERT INPUT TO BINARY
	LXI	D,MAXCYL
	JMP	TSUB		;TEST CYL ADR, EXIT




;	---INITIALIZE THE DIRECTORY---
;
;
CLRDIR	EQU	$
;
	IF	NOT (DRSIZE AND 1)	;IF 2 LOGICAL DRIVES
	PRNT	MSG37		;PRINT OPTION LIST
	MVI	A,1
	CALL	RCB		;GET OPER RESPONSE
	CPI	'M'
	JZ	LOOP		;RETURN TO MAIN MENU
	CPI	'1'
	JZ	ONE		;INIT 1ST DRIVE
	CPI	'2'
	JZ	TWO		;INIT 2ND DRIVE
	CPI	'B'
	JNZ	INV		;INVALID INPUT
; INITIALIZE BOTH DRIVES
BOTH:	CALL	CDSET		;DO SETUP
	LXI	H,0
	CALL	CAC		;1ST DRIVE
	LXI	H,1
	CALL	CAC
	LXI	H,MAXCYL/2	;2ND DRIVE
	CALL	CAC
	LXI	H,MAXCYL/2+1
	CALL	CAC
	JMP	CDEND		;DONE
; INITIALIZE 1ST DRIVE
ONE:	CALL	CDSET		;DO SETUP
	LXI	H,0
	CALL	CAC		;CLEAR A CYLINDER
	LXI	H,1
	CALL	CAC
	JMP	CDEND		;DONE
; INITIALIZE 2ND DRIVE
TWO:	CALL	CDSET		;DO SETUP
	LXI	H,MAXCYL/2
	CALL	CAC
	LXI	H,MAXCYL/2+1
	CALL	CAC
	ENDIF
;
	IF	DRSIZE AND 1	;IF SINGLE LOGICAL DRIVE
	CALL	CRLF		;DO CRLF
	CALL	CDSET		;DO SETUP
	LXI	H,0
CD1:	CALL	CAC		;CLEAR A CYL
	LHLD	CYL
	INX	H		;INCR CYL ADR
	MOV	A,L
	CPI	4
	JC	CD1		;JIF NOT DONE
	ENDIF
;
CDEND:	PRNT	MSG7		; 'INIT DONE'
	MVI	A,32
	STA	SECTBL+32	;RESTORE SECTOR 33
	CALL	STZ		;SEEK TO TRACK ZERO
	JMP	LOOP		;DO NEXT CMD
;
;   CLEAR A CYLINDER
;
CAC:	SHLD	CYL		;SAVE CYL ADR
	CALL	SEEK		;SEEK TO TARGET CYL
;
CAC1:	CALL	HDSEL		;HEAD SELECT
	CALL	WAT		;WRITE A TRACK
	LXI	H,HEAD
	INR	M		;INCR HEAD #
	MOV	A,M
	CPI	MAXHD		;MAX HEAD
	JC	CAC1		;JIF CON'T ON SAME CYL
	MVI	M,0		;RESET HEAD #
	RET
;
;   SETUP
;
CDSET:	CALL	TKZ		;RESTORE
	LXI	H,WRTCODE
	CALL	SQUIRT		;LOAD WRITE M/CODE
	LXI	H,0
	SHLD	CYL		;INIT CYL ADR
	SHLD	HEAD		;..HEAD & SECT
	LXI	H,0E5E5H
	CALL	FDB		;FILL DATA BFR = E5'S
	MVI	A,-1
	STA	SECTBL+32	;FOR 32 SECTORS
	JMP	HDSEL		;SLCT 1ST HEAD, EXIT

	PAGE


