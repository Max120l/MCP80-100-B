	LXI	B,(MAXSEC+1) SHL 8	;B = SECT CNT, C = ERROR CNT
;
SPR1:	MOV	A,M		;A = SECT ERROR CNT
	ORA	A
	JZ	SPR2		;JIF THIS SECT OK
	INR	C		;INCR ERROR CNT
	MVI	A,MAXSEC+1
	SUB	B		;CALC SECT ADR
	STA	SECADR		;SAVE ADR OF BAD SECTOR
;
SPR2:	INX	H		;INCR TBL ADR
	DCR	B		;DECR SECT CNT
	JNZ	SPR1
	MOV	A,C		;A = # BAD SECTS
	ORA	A
	RZ			;RIF ALL SECTORS OK
	LXI	H,EBH		;ERROR BY HEAD TABLE
	LDA	HEAD
	CALL	WINDX		;INDEX INTO THE TABLE
	XCHG			;H/L = ERROR COUNT
	MVI	B,0
	DAD	B		;ADD TO ERROR COUNT
	XCHG	
	MOV	M,D		;PUT COUNT BACK INTO TABLE
	DCX	H
	MOV	M,E
	LHLD	TOTAL
	DAD	B		;UPDATE TOTAL ERROR COUNT
	SHLD	TOTAL
	MOV	A,C
	DCR	A
	STA	COUNT		;SAVE ERROR COUNT
	JZ	SPR3		;JIF HAD ONE ERROR
	LHLD	MULTI
	INX	H		;INCR MUTLI SECTOR ERROR CNT
	SHLD	MULTI
;
