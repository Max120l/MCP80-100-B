;	---FORMAT---
;
;
FORMAT:	CALL	CRLF		;DO CR.LF
	LXI	H,RWEC		;START OF ERROR COUNT
	MVI	B,ECSIZ		;NUM BYTES
	XRA	A
FMT0:	MOV	M,A		;CLEAR ERROR COUNTS
	INX	H
	DCR	B
	JNZ	FMT0
;
	CALL	TKZ		;RESTORE
	CALL	SETUP		;SET START CYL/HEAD
	CALL	SEEK		;SEEK TO 1ST CYL
	CALL	NXP		;PRINT START CYL/HEAD
;
FMT1:	MVI	A,10
	STA	FCNT		;SET FMT RETRY COUNT
;
FMT2:	CALL	WGM		;WRITE GRAY MARKS
	CALL	WHDR		;WRITE HDR INFO
	CALL	VHDR		;VERIFY HDR INFO
	JZ	FMT3		;JIF HDRS OK
	LXI	H,FCNT
	DCR	M		;DECR RETRY COUNT
	JNZ	FMT2		;JIF RETRY FMT
;
FMT3:	CALL	WCD		;DO WORST CASE DATA TEST
	CALL	SPARE		;SPARE BAD SECTS (IF NECESSARY)
	CALL	NXTK		;GOTO NEXT TRACK
	JC	FMT1		;JIF CON'T FMT
	CALL	STZ		;MOVE HEADS TO CYL ZERO
;
;   FORMATTING DONE, PRINT SCOREBOARD
;
SCORE:	PRNT	MSG4		; 'FINISHED...'
	LHLD	TOTAL		;TOTAL NUM ERRORS
	MOV	A,H
	ORA	L
	JNZ	SCR1		;JIF HAD FMT ERRORS
	PRNT	MSG5		; '...NO ERRORS'
	JMP	LOOP		;DO NEXT CMD
;
SCR1:	PRNT	MSG8		; '...ERRORS DETECTED'
	LHLD	TOTAL
	CALL	DEC		;PRINT TOTAL ERROR COUNT
	PRNT	MSG9		; 'TOTAL ERRORS'
	LHLD	TOTAL
	LXI	D,128+1
	CALL	OKTST		;TEST ERROR LIMITS
;
	LHLD	SPARED		;NUM SECTORS SPARED
	CALL	DEC		;..PRINT COUNT
	PRNT	MSG10		; 'SECTORS SPARED'
;
	LHLD	MULTI		;NUM OF MULTI-SECTOR ERRORS
	CALL	DEC		;..PRINT COUNT
	PRNT	MSG11		; 'MULTI SECTOR ERRORS'
	LHLD	MULTI
	MOV	A,H
	ORA	L
	JZ	SCR2		;JIF NO ERRORS
	PRNT	MSG19		; 'RUN RECLAIM'
SCR2:	CALL	CRLF
	CALL	CRLF		;DO 2 CR.LF
; PRINT ERROR COUNTS BY HEAD
	LDA	BGNHED		;1ST HEAD
	STA	COUNT		;INIT HEAD #
SCR3:	LDA	COUNT
	LXI	H,EBH		;TBL OF ERRS BY HEAD
	CALL	WINDX		;INDEX INTO TBL
	XCHG			;H/L = ERROR COUNT
	PUSH	H		;..SAVE IT
	CALL	DEC		;PRINT ERROR COUNT
	PRNT	MSG20		; 'ON HEAD'
	LDA	COUNT
	ADI	'0'
	MOV	E,A
	CPM	F@CO		;PRINT HEAD #
	POP	H		;H/L = ERROR COUNT
	LXI	D,16+1
	CALL	OKTST		;TEST ERROR LIMITS
	LXI	H,COUNT
	INR	M		;INCR HEAD #
	MOV	A,M
	LXI	H,ENDHED	;LAST HEAD
	CMP	M
	JC	SCR3		;JIF DO NEXT HEAD
	PRNT	MSG22		; 'STRIKE ANY KEY'
	CPM	F@CI		;GET OPER RESPONSE
	CALL	CRLF		;DO CR.LF
	JMP	LOOP		;DO NEXT CMD




;	---WRITE GRAY MARKS---
;
;   'WGM' CLEANS THE TRACK (WRITES ALL ZEROS) & THEN ATTEMPTS
;   TO WRITE 33 GRAY MARKS. A GRAY MARK IS USED TO DENOTE THE
;   START OF A SECTOR.
;
;
WGM:	MVI	A,10
	STA	GCNT		;SET RETRY COUNT
	LXI	H,CTCODE
	CALL	SQUIRT		;LOAD CLEAN TRACK M/CODE
	LXI	H,GMCODE
	CALL	SQUIRT		;LOAD GRAY MARK M/CODE
	CALL	CDB		;CLEAR DATA BFR
;
	MVI	A,CBENB+BANK1
	OUT	CTCSR		;ENB CMP BFR
	XRA	A
	OUT	CTBFR		;INIT BFR ADR
WGM1:	OUT	CTDP		;PUT INCR CNT INTO CMP BFR
	INR	A
	CPI	16
	JC	WGM1
;
WGM2:	CALL	CLNTK		;CLEAN (CLEAR) A TRACK
	DI			;INHIBIT INTPS
	IN	EXTCMD		;RESET RAW INDEX F/F
;
WGM3:	IN	DRCSR		;DRIVE STATUS
	ANI	RAWINDX
	JZ	WGM3		;WAIT FOR RAW INDEX
	IF	FASTCPU
	MVI	A,2
	DCR	A
	JNZ	$-1		;DELAY ABOUT 7 USEC
	ENDIF
	MVI	A,GMSA
	OUT	CTBFR		;SET BFR ADR
	MVI	A,START+BANK1
	OUT	CTCSR		;START WRITE
;
	IN	EXTCMD		;CLEAR RAW INDEX F/F
WGM4:	IN	DRCSR		;DRIVE STATUS
	ANI	RAWINDX
	JZ	WGM4		;WAIT FOR 2ND RAW INDEX
	MVI	A,DC1
	DCR	A
	JNZ	$-1		;ENSURE WRITE OVERLAP
	OUT	CTCSR		;STOP WRITE
	IF	ENBINT		;IF INTPS ENABLED
	EI
	ENDIF
	IN	DRCSR		;DRIVE STATUS
	ANI	WRTFLT
	JNZ	WGM5		;JIF HAD WRITE FAULT
	CALL	CNTGM		;COUNT GRAY MARKS
	RZ			;RIF OK
	MOV	A,B
	STA	COUNT		;SAVE G.M. COUNT
	JMP	WGM6
;
WGM5:	CALL	CLRDF		;CLEAR DRIVE FAULT
	XRA	A
	STA	COUNT		;CLEAR ERROR COUNT
;
WGM6:	LXI	H,GCNT
	DCR	M		;DECR RETRY COUNT
	JNZ	WGM2		;JIF RETRY WRITE
	PRNT	MSG24		;PRINT ERROR MSG
	LDA	COUNT
	CALL	BTH		;PRINT G.M. COUNT
	CALL	PCA		;PRINT CYL ADR
	CALL	PHN		;PRINT HEAD #
	PRNT	MSG25		; 'UNRECOVERABLE...'
	JMP	LOOP		;ABORT!




;	---WRITE HEADERS---
;
;   'WHDR' WRITES THE HEADER INFORMATION FOR EACH SECTOR.
;   THE HEADER CONTAINS TWO BYTES FOR CYLINDER, ONE BYTE
;   FOR THE HEAD, & ONE BYTE FOR THE SECTOR.
;
;
WHDR:	LXI	H,FMTCODE
	CALL	SQUIRT		;SET FMT M/CODE
;
WHDR1:	LXI	H,SECTBL	;SECTOR TABLE ADR
	SHLD	TBLADR		;  SAVE TBL ADR
	MOV	A,M		;1ST SECTOR ADR
	STA	SECADR		;  SAVE IT
	XRA	A
	DI			;INHIBITS INTPS
	OUT	CTCSR		;CLEAR INDEX F/F
;
WHDR2:	IN	CTCSR		;CTLR STATUS
	ANI	INDEX
	JZ	WHDR2		;WAIT FOR INDEX
;
WHDR3:	LXI	H,FTBL
	CALL	DORW		;FORMAT A SECTOR
	CALL	BTA		;BUMP TABLE ADR
	JNZ	WHDR3		;WRITE NEXT HDR
	IF	ENBINT		;IF INTPS ENABLED
	EI
	ENDIF
	RET




;	---VERIFY HEADERS---
;
;   'VHDR' VERIFYS HEADERS WRITTEN BY 'WHDR'
;
;
VHDR:	LXI	H,VERCODE
	CALL	SQUIRT		;LOAD VERIFY M/CODE
	LXI	H,SECTBL	;SECTOR TABLE ADR
	SHLD	TBLADR		;..SAVE IT
	MOV	A,M
	STA	SECADR		;SET 1ST SECT ADR
	XRA	A
	DI			;INHIBIT INTPS
	OUT	CTCSR		;RESET INDEX F/F
;
VHDR1:	IN	CTCSR		;CTLR STATUS
	ANI	INDEX
	JZ	VHDR1		;WAIT FOR INDEX
;
VHDR2:	LXI	H,VTBL
	CALL	DORW		;VERIFY THE HEADER
	RNZ			;RIF HEADER BAD
	CALL	BTA		;BUMP TABLE ADR
	JNZ	VHDR2		;TEST NEXT HDR
	IF	ENBINT		;IF INTPS ENABLED
	EI
	ENDIF
	RET





;	---WORST CASE DATA TEST---
;
;   'WCD' WRITES A WORST CASE DATA PATTERN ONTO EVERY SECTOR
;   OF A TRACK. EACH SECTOR IS READ TWICE. THE DATA PATTERN IS
;   ROTATED ONE POSITION & THE DATA IS REWRITTEN. THE COMPLETE
;   PROCESS IS REPEATED 16 TIMES. ERRORS ARE ACCUMULATED FOR
;   LATER USE BY THE SECTOR SPARING ROUTINE 'SPARE'.
;
;
WCD:	CALL	CEC		;CLEAR ERROR COUNTS
	LXI	H,WORST
	SHLD	DATA		;INIT WORST CASE DATA PATTERN
	MVI	A,16
	STA	RWCNT		;SET LOOP COUNT
	LXI	H,WRTCODE
	CALL	SQUIRT		;LOAD WRITE M/CODE
	LXI	H,RDCODE
