	ORA	A
	RNZ			;CAN'T SPARE, 33RD SECTOR BAD
	LHLD	SPARED
	INX	H		;INCR # SECTORS SPARED
	SHLD	SPARED
	LXI	H,FMTCODE
	CALL	SQUIRT		;LOAD FMT M/CODE
; CALC REAL SECTOR ADR
	LXI	H,SECTBL	;TBL OF SECT ADRS
	LDA	SECADR		;A = LOGICAL SECTOR TO BE SPARED
	MVI	B,0		;B = PHYSICAL SECTOR ADR
SPR4:	CMP	M
	JZ	SPR5		;JIF FOUND PHYSICAL SECTOR
	INX	H
	INR	B
	JMP	SPR4
