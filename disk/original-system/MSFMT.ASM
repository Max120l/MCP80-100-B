	CPI	61H
	RC			;RIF NOT L/C CHAR
	CPI	7BH	
	RNC			;RIF NOT L/C CHAR
	SUI	20H		;DO CONVERSION
	RET




;	---PRINT DECIMAL---
;
;   PRINT THE CONTENTS OF 'H/L' IN DECIMAL. LEADING
;   ZEROS ARE CONVERTED TO SPACES.
;
;
DEC:	PUSH	H		;SAVE COUNT
	CALL	CRLF		;DO CR.LF
	POP	H
	MOV	A,L
	ORA	H
	JNZ	DEC2		;JIF VALUE <> 0
	MVI	E,' '
	MVI	B,4
DEC1:	CPM	F@CO		;PRINT 4 SPACES
	DCR	B
	JNZ	DEC1
	MVI	E,'0'
	CPM	F@CO		;PRINT 1 ZERO
	RET
;
DEC2:	MVI	B,0		;RESET NON-ZERO FLAG
	LXI	D,10000
	CALL	DX		;PRINT 10K'S
	LXI	D,1000
	CALL	DX		;PRINT 1K'S
	LXI	D,100
	CALL	DX		;PRINT 100'S
	LXI	D,10
	CALL	DX		;PRINT 10'S
	MOV	A,L
	ADI	'0'		;MAKE NUM ASCII
	MOV	E,A
	JMP	DX4		;PRINT 1'S, THEN EXIT
;
;
;
DX:	MVI	C,0		;NUMBER OF "N"
;
DX1:	MOV	A,L		; (H/L) = (H/L)-(D/E)
	SUB	E
	MOV	L,A
	MOV	A,H
	SBB	D
	MOV	H,A
	JC	DX2
	INR	C		;INCR NUM OF "N"
	JMP	DX1
;
DX2:	DAD	D		;RESTORE #
	MOV	A,C
	ADI	'0'		;CONVERT NUM TO ASCII
	MOV	E,A
	CPI	'0'
	JZ	DX3		;JIF NUM WAS ZERO
	INR	B		;SET FLAG = PRINT ZEROS
	JMP	DX4
;
DX3:	MOV	A,B
	ORA	A
	JNZ	DX4		;JIF PRINT ZEROS
	MVI	E,' '		;LEADING ZEROS ARE SPACES
;
DX4:	CPM	F@CO		;PRINT THE NUM
	RET




