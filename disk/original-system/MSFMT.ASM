	ORA	L
	JNZ	WSC1		;JIF CON'T WAITING
	DCR	B
	JNZ	WSC1		;CON'T WAITING
	PRNT	MSG34		; 'SEEK FAILED'
	PRNT	MSG25		; 'UNRECOVERABLE ERROR'
	JMP	LOOP		;ABORT, SEEK FAILED TO FINISH
;
WSC2:	RAR
	STA	DSTAT		;SAVE DRIVE STATUS
	RET




