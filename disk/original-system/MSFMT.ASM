	LXI	H,CYL
	MVI	B,32
	CALL	FSH		;SPARE THE BAD SECTOR
	CALL	PSA		;PRINT SECT ADR
	PRNT	MSG21		; '...SPARED'
	LDA	COUNT
	ORA	A
	RZ			;RIF HAD ONE BAD SECT
