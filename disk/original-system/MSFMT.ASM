;	---SEEK---
;
;
SEEK:	CALL	RDY		;DRIVE READY ?  (RIF YES)
	LHLD	CYL		;TARGET CYL
	XCHG
	LHLD	CCA		;CURRENT CYL 
	LDA	CHA		;CURRENT HEAD #
	MOV	B,A		;..SAVE FOR LATER USE
	CALL	SUBT		; (H/L) - (D/E)
	RZ			;DON'T SEEK IF SAME CYL
	MOV	A,H
	RAL
	JNC	SEK1		;JIF SEEK OUTWARD
; SEEK INWARD
	MOV	A,L		;MAKE SEEK COUNT POSITIVE
	CMA			  ;
	MOV	L,A		  ;
	MOV	A,H		  ;
	CMA			  ;
	MOV	H,A		  ;
	INX	H		  ;
	MOV	A,B		;A = HEAD #
	ORI	SKIN
	OUT	EXTCMD		;SET SEEK DIRC = INWARD
	JMP	SEK2
; SEEK OUTWARD
SEK1:	MOV	A,B		;A = HEAD #
	OUT	EXTCMD		;SET SEEK DIRC = OUTWARD
; EXECUTE SEEK
SEK2:	MOV	A,L
	OUT	LOSC		;SET SEEK COUNT, LSB
	MOV	A,H
	OUT	HISC		;   * MSB
	MVI	A,3
	OUT	DRCSR		;ISSUE SEEK CMD
	CALL	WSC		;WAIT FOR SEEK COMPLETE
	LHLD	CYL
	SHLD	CCA		;UPDATE CURR CYL ADR
	RET




