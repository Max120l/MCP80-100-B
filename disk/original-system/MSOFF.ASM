	TITLE	'MSOFF -- MOVE HEADS TO LANDING ZONE'

;	10-27-82



;   'MSOFF' IS USED TO POSITION THE HEADS OF A MINISCRIBE HARD DISK
;   DRIVE OVER THE INNERMOST CYLINDER. THIS PROGRAM MAY BE RUN
;   BEFORE REMOVING POWER FROM THE DRIVE. THIS PROGRAM **MUST**
;   BE RUN BEFORE SHIPPING THE DRIVE. AN  XCOMP STS/STR HARD DISK
;   CONTROLLER IS USED.




;	---PROGRAM CONFIGURATION---
;
;
;   THE FOLLOWING STATEMENTS ARE USED TO CONFIGURE THE PROGRAM.
;
;	1. TEST -- SET THIS 'FALSE' BEFORE USING THE PROGRAM.
;
;	2. S100 -- SET THIS 'TRUE' IF YOU ARE USING A CONTROLLER WITH
;	   AN S-100 BUS INTERFACE (STS). SET THIS 'FALSE' IF YOU ARE
;	   USING A CONTROLLER WITH THE RIBBON CABLE INTERFACE (STR).
;
;	3. FASTKZ -- SET THIS 'TRUE' IF YOU ARE USING A MINISCRIBE HARD
;	   DISK DRIVE. SET THIS 'FALSE' IF YOU ARE NOT USING A MINISCRIBE
;	   DRIVE.
;
;		** WARNING -- SETTING 'FASTKZ' TO 'TRUE' FOR DRIVES
;			      OTHER THAN A MINISCRIBE MAY CAUSE SERIOUS
;			      MECHANICAL DRIVE FAILURES!
;
;
;	4. DRSIZE -- SET THIS TO A VALUE OF 1, 2, 3, OR 4 DEPENDING UPON
;	   THE TYPE OF DRIVE YOU ARE USING.
;
;		1 =  5 Megabyte MS-1006
;		2 = 10 Megabyte MS-1012
;		3 =  8 Megabyte MS-4010
;		4 = 20 Megabyte MS-4020
;
;
;
;
FALSE	EQU	0		;DEFINE FALSE
TRUE	EQU	NOT FALSE	;..TRUE
;
TEST	EQU	FALSE		;NOT TESTING
;
S100	EQU	TRUE		;S-100 CONTROLLER
;
FASTKZ	EQU	TRUE		;FAST RESTORE
;
DRSIZE	EQU	4		;16 MEG MS-4020




;	---EQUATES---
;
;
STRT	EQU	100H		;PROGRAM START ADDRESS
STACK	EQU	100H		;STACK ADDRESS
LMSK	EQU	0FFH		;LSB MASK
WBOOT	EQU	0		;CPM WARM BOOT
BDOS	EQU	5		;BDOS ENTRY POINT
;
	IF	DRSIZE LT 3	;IF USING MS-1006 OR MS-1012
LZONE	EQU	325		;LANDING ZONE
MAXTKZ	EQU	350		;RESTORE COUNT
	ELSE			;IF USING MS-4010 OR MS-4020
LZONE	EQU	510		;LANDING ZONE
MAXTKZ	EQU	511		;RESTORE COUNT
	ENDIF
;
ROMCTL	EQU	0FH		;ROM CONTROL PORT
ROMON	EQU	80H		;ENABLES ROM
DEBUG	EQU	0F000H		;ROM DEBUG ENTRY POINT
;
;   DRIVE COMMANDS
;
SKCMD	EQU	3		;SEEK COMMAND
SKOUT	EQU	1		;SEEK DIRECTION = OUTWARD
SKIN	EQU	3		;..INWARD
NOPC	EQU	40H		;NO PRE-COMPENSATION
LOWRT	EQU	80H		;LOW WRITE CURRENT
;
;   DRIVE STATUS
;
READY	EQU	1		;DRIVE READY
WRTFLT	EQU	2		;WRITE FAULT
TK00	EQU	4		;TRACK ZERO
RAWINDX	EQU	20H		;RAW INDEX
;
;   CONTROLLER COMMANDS
;
BANK0	EQU	0		;BANK 0 SELECT
BANK1	EQU	1		;BANK 1 SELECT
DBENB	EQU	2		;DATA BUFFER ENABLE
CBENB	EQU	4		;COMPARE BUFFER ENABLE
START	EQU	8		;START COMMAND
;
;   CONTROLLER STATUS
;
INDEX	EQU	10H		;DELAYED INDEX
SECTOR	EQU	20H		;SECTOR
;
;   DRIVE/CONTROLLER I/O
;
CBASE	EQU	60H		;BASE ADR OF THE CONTROLLER
;
	IF	S100	; IF S-100 BUS COMPUTER
DRCSR	EQU	CBASE		;DRIVE COMMAND/STATUS
EXTCMD	EQU	CBASE+1		;EXTENDED COMMNAND REGISTER
LOSC	EQU	CBASE+2		;SEEK COUNT, LSB
HISC	EQU	CBASE+3		;  * MSB
CTCSR	EQU	CBASE+4		;CONTROLLER COMMAND/STATUS
CTBFR	EQU	CBASE+5		;CONTROLLER BUFFER ADDRESS
CTDP	EQU	CBASE+6		;CONTROLLER DATA PORT
	ELSE		; IF RIBBON CABLE INTERFACE
DRCSR	EQU	CBASE+7		;DRIVE COMMAND/STATUS
EXTCMD	EQU	CBASE+6		;EXTENDED COMMNAND REGISTER
LOSC	EQU	CBASE+5		;SEEK COUNT, LSB
HISC	EQU	CBASE+4		;  * MSB
CTCSR	EQU	CBASE+3		;CONTROLLER COMMAND/STATUS
CTBFR	EQU	CBASE+2		;CONTROLLER BUFFER ADDRESS
CTDP	EQU	CBASE+1		;CONTROLLER DATA PORT
	ENDIF
;
;   ASCII CHARACTERS 
;
CR	EQU	0DH		;CARRIAGE RETURN
LF	EQU	0AH		;LINE FEED
BELL	EQU	7		;DING!
ESC	EQU	1BH		;ESCAPE KEY
;
;   CPM FUNCTION CODES
;
F@CI	EQU	1		;CONSOLE INPUT
F@CO	EQU	2		;CONSOLE OUTPUT
F@PRT	EQU	9		;PRINT MESSAGES

	PAGE



;	============
;	** MACROS **
;	============



;	---CALL BDOS---
;
;
CPM	MACRO	FC
	MVI	C,FC		;; C = FUNCTION CODE
	CALL	BDOS		;; DO CPM FUNCTION
	ENDM




;	---PRINT MESSAGES---
;
;
PRNT	MACRO	MSG
	LXI	D,MSG		;; ADR OF THE MSG
	CPM	F@PRT		;; PRINT THE MSG
	ENDM

	PAGE


	ORG	STRT



;	---PROGRAM ENTRY POINT---
;
;
BGN:	LXI	SP,STACK
	PRNT	MSG1		;SAY HELLO
	CALL	COFF		;STOP ANY PRIOR ACTIVITY
	MVI	A,1
	OUT	EXTCMD		;SLCT THE DRIVE
	INR	A
	OUT	DRCSR		;ENABLE THE INTERFACE
;
LOOP:	CALL	TKZ		;RESTORE
	JNZ	ERROR		;JIF RESTORE FAILED
	CALL	SEEK		;SEEK TO INNER CYL
	JNZ	ERROR		;JIF SEEK FAILED
;
;   HEADS ARE NOW IN SHIP POSITION
;
DONE:	PRNT	MSG2		;SAY GOODBYE
	CALL	COFF		;TURN OFF DRIVE/CTLR
	IF	TEST	;; IF WE ARE TESTING
	JMP	0		;WARM BOOT
	ELSE		;; NORMAL MODE
	DI			;INHIBIT INTERRUPTS
	JMP	$		;DON'T DO ANYTHING ELSE
	ENDIF
;
;   ERROR RETRY ROUTINE
;
ERROR:	PRNT	MSG4		; 'TYPE ANY CHAR...'
	CPM	F@CI		;WAIT FOR OPER
	CPI	3
	JZ	WBOOT		;ABORT
	PRNT	MSG5		;DO CR.LF
	JMP	LOOP		;RETRY




;	---REZERO---
;
;
	IF	FASTKZ		;IF USE FAST RESTORE ALGORITHM

TKZ:	IN	DRCSR		;DRIVE STATUS
	ANI	TK00		;TRACK ZERO FLAG
	XRI	TK00		;..MAKE IT LOW-TRUE
	RZ			;RIF ALREADY AT TRACK ZERO
;
	CALL	RDY		;DRIVE READY ?
	RNZ			;ABORT, DRIVE NOT READY
	MVI	A,MAXTKZ AND LMSK
	OUT	LOSC		;SET LSB OF SEEK COUNT
	MVI	A,MAXTKZ SHR 8
	OUT	HISC		;SET MSB
	MVI	A,SKOUT
	OUT	EXTCMD		;SET SEEK DIRC = OUTWARD
	MVI	A,SKCMD
	OUT	DRCSR		;ISSUE SEEK CMD
	LXI	H,0
	MVI	B,10
;
TKZ1:	IN	DRCSR		;DRIVE STATUS
	ANI	TK00		;TRACK ZERO FLAG
	JNZ	TKZ2		;JIF AT TRACK ZERO
	DCX	H		;DECR TIME-OUT
	MOV	A,H
	ORA	L
	JNZ	TKZ1
	DCR	B
	JNZ	TKZ1
	OUT	HISC
	OUT	LOSC		;ZERO SEEK COUNTER
	PRNT	MSG6		; 'RESTORE FAILED'
	ORI	1		;SET ERROR FLAG
	RET
;
TKZ2:	XRA	A
	OUT	HISC
	OUT	LOSC		;ZERO SEEK COUNTER
	JMP	WSC		;WAIT FOR SEEK DONE, EXIT

	ENDIF



	IF	NOT FASTKZ	;NORMAL RESTORE ALGORITHM

TKZ:	LXI	B,MAXTKZ	;INIT FIND COUNT
;
TKZ1:	CALL	RDY		;DRIVE READY ?
	RNZ			;RIF DRIVE NOT RDY
	IN	DRCSR		;DRIVE STATUS
	ANI	TK00		;TRACK ZERO INDICATOR
	XRI	TK00		;  * MAKE IT LO-TRUE
	RZ			;RIF AT TRACK ZERO
	DCX	B		;DECR FIND COUNT
	MOV	A,B
	ORA	C
	JZ	TKZ2		;JIF REZERO FAILED
	XRA	A
	OUT	HISC		;CLEAR SEEK CNT, MSB
	INR	A
	OUT	LOSC		;SET SEEK COUNT = 1
	OUT	EXTCMD		;SET DIRC = OUT
	MVI	A,SKCMD
	OUT	DRCSR		;ISSUE STEP CMD
	CALL	WSC		;WAIT FOR SEEK DONE
	JMP	TKZ1
;
TKZ2:	PRNT	MSG6		; 'REZERO FAILED'
	ORI	1		;SET ERROR FLAG
	RET

	ENDIF




;	---SEEK---
;
;
SEEK:	CALL	RDY		;DRIVE READY ?
	RNZ			;RIF DRIVE NOT RDY
	MVI	A,LZONE AND 0FFH
	OUT	LOSC		;SET SEEK CNT, LSB
	MVI	A,LZONE SHR 8
	OUT	HISC		;SET SEEK CNT, MSB
	MVI	A,3
	OUT	EXTCMD		;SET SEEK DIRECTION = INWARD
	OUT	DRCSR		;ISSUE SEEK CMD
;
;   WAIT FOR SEEK COMPLETE
;
WSC:	IN	DRCSR		;DRIVE STATUS
	RAL
	JNC	WSC		;WAIT FOR SEEK DONE
	XRA	A
	RET




;	---DRIVE READY TEST---
;
;
RDY:	IN	DRCSR		;DRIVE STATUS
	ANI	1
	XRI	1
	RZ			;RIF DRIVE RDY
	PRNT	MSG3		; 'DRIVE NOT RDY'
	ORI	1		;SET ERROR FLAG
	RET




;	---TURN DRIVE/CONTROLLER OFF---
;
;
COFF:	XRA	A
	OUT	CTCSR		;STOP ANY PRIOR ACTIVITY
	OUT	DRCSR		;DISABLE THE INTERFACE
	OUT	EXTCMD		;DE-SELECT THE DRIVE
	RET




;	---MESSAGES---
;
;
MSG1:	DB	CR,LF,LF
	DB	'MSOFF -- Vers 1.2',CR,LF
	DB	'27-Oct-82',CR,LF,'$'
;
MSG2:	DB	CR,LF,'* Heads are over Landing Zone',CR,LF
	DB	'  OK to remove Drive Power!',CR,LF,'$'
;
MSG3:	DB	BELL,CR,LF,'* Drive not Ready',CR,LF,'$'
;
MSG4:	DB	CR,LF,'  Type CTRL-C to ABORT or any other character to RETRY $'
;
MSG5:	DB	CR,LF,'$'
;
MSG6:	DB	BELL,CR,LF,'* Restore Failed',CR,LF,'$'




	END
