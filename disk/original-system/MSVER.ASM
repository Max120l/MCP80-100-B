	TITLE	'MSVER -- MINISCRIBE VERIFY'

;	10-27-82


;   'MSVER' IS USED TO READ (VERIFY) MINISCRIBE HARD DISK DRIVES. BOTH SOFT
;   & HARD ERRORS ARE REPORTED. SOFT ERRORS ARE DEFINED AS THE ABILITY TO
;   READ A SECTOR WITH LESS THAN 10 RETRIES. HARD ERRORS ARE DEFINED AS
;   THE INABILITY TO READ A SECTOR WITHIN 10 RETRIES. THE ERRORS WILL BE
;   REPORTED AS FOLLOWS:
;
;
;	1)   * Soft Read Error  Cyl=xx  Hd=xx  Sect=xx  Retries=xx
;
;	2)   * Hard Read Error  Cyl=xx  Hd=xx  Sect=xx  Error=[RNF/CRC]
;
;	     WHERE --	Cyl = Cylinder Address	:
;			 Hd = Head Number	:  Numbers are in Hex
;		       Sect = Sector Address	:
;		        ----------------------
;			RNF = Record not Found
;			CRC = Data CRC Error
;
;
;   NOTE -- HITTING THE "ESC" KEY WHILE RUNNING WILL ABORT VERIFICATION.





;	---PROGRAM CONFIGURATION---
;
;
;   THE FOLLOWING STATEMENTS ARE USED TO CONFIGURE THE PROGRAM.
;
;	1. TEST -- SET THIS 'FALSE' BEFORE USING THE PROGRAM. 
;
;	2. S100 -- SET THIS 'TRUE' IF YOU ARE USING A CONTROLLER WITH
;	   AN S-100 BUS INTERFACE (STS). SET THIS 'FALSE' IF YOU ARE
;	   USING A CONTROLLER WITH THE RIBBON CABLE INTERFACE (STR).
;
;	3. FASTCPU -- SET THIS 'TRUE' IF YOUR PROCESSOR IS RUNNING AT
;	   4 MHZ. SET THIS 'FALSE' IF YOUR PROCESSOR IS RUNNING AT
;	   2 MHZ.
;
;	4. FASTKZ -- SET THIS 'TRUE' IF YOU ARE USING A MINISCRIBE HARD
;	   DISK DRIVE. SET THIS 'FALSE' IF YOU ARE NOT USING A MINISCRIBE
;	   DRIVE.
;
;		** WARNING -- SETTING 'FASTKZ' TO 'TRUE' FOR DRIVES
;			      OTHER THAN A MINISCRIBE MAY CAUSE SERIOUS
;			      MECHANICAL DRIVE FAILURES!
;
;
;	5. DRSIZE -- SET THIS TO A VALUE OF 1, 2, 3, OR 4 DEPENDING UPON
;	   THE TYPE OF DRIVE YOU ARE USING.
;
;		1 =  5 Megabyte MS-1006
;		2 = 10 Megabyte MS-1012
;		3 =  8 Megabyte MS-4010
;		4 = 20 Megabyte MS-4020
;
;
;
;
FALSE	EQU	0		;DEFINE FALSE
TRUE	EQU	NOT FALSE	;..TRUE
;
TEST	EQU	FALSE		;NOT TESTING
;
S100	EQU	TRUE		;S-100 BUS COMPUTER
;
FASTCPU	EQU	TRUE		;RUNNING AT 4 MHZ
;
FASTKZ	EQU	TRUE		;FAST RESTORE
;
DRSIZE	EQU	4		;16 MEG MS-4020






;	---EQUATES---
;
;
STRT	EQU	100H		;PROGRAM START ADDRESS
STACK	EQU	100H		;STACK ADDRESS
LMSK	EQU	0FFH		;LSB MASK
WBOOT	EQU	0		;CPM WARM BOOT
BDOS	EQU	5		;BDOS ENTRY POINT
DEBUG	EQU	0F000H		;DEBUG ENTRY POINT
RPT	EQU	80H		;REPEAT FLAG
;
VSA	EQU	8		;VERIFY START ADDRESS
VCA	EQU	1BH		;VERIFY COMPARE ADDRESS
VCNT	EQU	10		;VERIFY RETRY COUNT
;
	IF	FASTCPU
SKEW	EQU	10		;FORMAT INTERLACE FACTOR
	ELSE
SKEW	EQU	16		;FORMAT INTERLACE FACTOR
	ENDIF
;
;
	IF	DRSIZE EQ 1	;IF 5 MEG MS-1006
MAXHD	EQU	2		;NUMBER OF HEAD
MAXCYL	EQU	306		;NUMBER OF CYLINDERS
MAXTKZ	EQU	350		;RESTORE COUNT
	ENDIF
;
	IF	DRSIZE EQ 2	;IF 10 MEG MS-1012
MAXHD	EQU	4		;NUMBER OF HEADS
MAXCYL	EQU	306		;NUMBER OF CYLINDERS
MAXTKZ	EQU	350		;RESTORE COUNT
	ENDIF
;
	IF	DRSIZE EQ 3	;IF 8 MEG MS-4010
MAXHD	EQU	2		;NUMBER OF HEADS
MAXCYL	EQU	480		;NUMBER OF CYLINDERS
MAXTKZ	EQU	511		;RESTORE COUNT
	ENDIF
;
	IF	DRSIZE EQ 4	;IF 16 MEG MS-4020
MAXHD	EQU	4		;NUMBER OF HEADS
MAXCYL	EQU	480		;NUMBER OF CYLINDERS
MAXTKZ	EQU	511		;RESTORE COUNT
	ENDIF
;
MAXSEC	EQU	32		;NUMBER OF SECTORS PER TRACK
;
;   DRIVE COMMANDS
;
SKCMD	EQU	3		;SEEK COMMAND
SKOUT	EQU	1		;SEEK DIRECTION = OUTWARD
SKIN	EQU	2		;..INWARD
NOPC	EQU	40H		;NO PRE-COMPENSATION
LOWRT	EQU	80H		;LOW WRITE CURRENT
;
;   DRIVE STATUS
;
READY	EQU	1		;DRIVE READY
WRTFLT	EQU	2		;WRITE FAULT
TK00	EQU	4		;TRACK ZERO
RAWINDX	EQU	20H		;RAW INDEX
;
;   CONTROLLER COMMANDS
;
BANK0	EQU	0		;BANK 0 SELECT
BANK1	EQU	1		;BANK 1 SELECT
DBENB	EQU	2		;DATA BUFFER ENABLE
CBENB	EQU	4		;COMPARE BUFFER ENABLE
START	EQU	8		;START COMMAND
;
;   CONTROLLER STATUS
;
INDEX	EQU	10H		;DELAYED INDEX
SECTOR	EQU	20H		;SECTOR
;
;   DRIVE/CONTROLLER I/O
;
CBASE	EQU	60H		;BASE ADR OF THE CONTROLLER
;
	IF	S100	; IF S-100 BUS COMPUTER
DRCSR	EQU	CBASE		;DRIVE COMMAND/STATUS
EXTCMD	EQU	CBASE+1		;EXTENDED COMMNAND REGISTER
LOSC	EQU	CBASE+2		;SEEK COUNT, LSB
HISC	EQU	CBASE+3		;  * MSB
CTCSR	EQU	CBASE+4		;CONTROLLER COMMAND/STATUS
CTBFR	EQU	CBASE+5		;CONTROLLER BUFFER ADDRESS
CTDP	EQU	CBASE+6		;CONTROLLER DATA PORT
	ELSE		; IF RIBBON CABLE INTERFACE
DRCSR	EQU	CBASE+7		;DRIVE COMMAND/STATUS
EXTCMD	EQU	CBASE+6		;EXTENDED COMMNAND REGISTER
LOSC	EQU	CBASE+5		;SEEK COUNT, LSB
HISC	EQU	CBASE+4		;  * MSB
CTCSR	EQU	CBASE+3		;CONTROLLER COMMAND/STATUS
CTBFR	EQU	CBASE+2		;CONTROLLER BUFFER ADDRESS
CTDP	EQU	CBASE+1		;CONTROLLER DATA PORT
	ENDIF
;
;   ASCII CHARACTERS 
;
CR	EQU	0DH		;CARRIAGE RETURN
LF	EQU	0AH		;LINE FEED
BELL	EQU	7		;DING!
BKSP	EQU	8		;BACKSPACE
ESC	EQU	1BH		;ESCAPE KEY
;
;   CPM FUNCTION CODES
;
F@CI	EQU	1		;CONSOLE INPUT
F@CO	EQU	2		;CONSOLE OUTPUT
F@PRNT	EQU	9		;PRINT MESSAGES
F@RCB	EQU	10		;READ CONSOLE BUFFER
F@REQ	EQU	11		;GET CONSOLE STATUS

	PAGE



;	============
;	** MACROS **
;	============



;	---CALL BDOS---
;
;
CPM	MACRO	FC
	CALL	SYSTEM		;; SYSTEM CALL ROUTINE
	DB	FC		;; CPM FUNCTION CODE
	ENDM




;	---PRINT MESSAGES---
;
;
PRNT	MACRO	MSG
	LXI	D,MSG		;; ADR OF THE MSG
	CPM	F@PRNT		;; PRINT THE MSG
	ENDM

	PAGE

	ORG	STRT	


;	==========================
;	** PROGRAM ENTRY POINT **
;	==========================
;
;
;
BGN:	LXI	SP,STACK	;USE INTERNAL STACK
	DI			;INHIBIT INTERRUPTS
	CALL	COFF		;STOP ANY PRIOR ACTIVITY
	PRNT	MSG1		;SAY HELLO
	MVI	A,1
	OUT	EXTCMD		;SLCT DRIVE ZERO
	INR	A
	OUT	DRCSR		;ENABLE INTERFACE BOARD
	CALL	BST		;BUILD SECTOR TABLE
;
;   COMMAND LOOP
;
LOOP:	LXI	SP,STACK	;RESET SP
	PRNT	MSG2		;PRINT MENU
	LDA	BGNHED
	CALL	BTH1		;PRINT START HEAD
	MVI	E,'-'
	CPM	F@CO		;PRINT SEPERATOR
	LDA	ENDHED		;END HEAD NUM
	DCR	A		;..ADJUST IT
	CALL	BTH1		;..PRINT IT
	PRNT	MSG2A		; 'CYLS = '
	LHLD	BGNCYL
	CALL	P3D		;PRINT START CYL
	MVI	E,'-'
	CPM	F@CO		;PRINT SEPERATOR
	LHLD	ENDCYL
	DCX	H
	CALL	P3D		;PRINT END CYL
	PRNT	MSG2B		; 'CMD?'
;
	MVI	A,1
	CALL	RCB		;GET OPER CMD
	CPI	'C'
	JZ	NEWCYL		;JIF GET NEW CYL LIMITS
	CPI	'H'
	JZ	NEWHED		;JIF GET NEW HEAD LIMITS
	CPI	'S'
	JZ	VERIFY		;JIF VERIFY THE DISK
	CPI	'X'
	JZ	XIT		;JIF EXIT TO CPM
;
;   INVALID INPUT
;
INV:	PRNT	MSG3		;PRINT 'INVALID INPUT'
	JMP	LOOP		;DO NEXT CMD
;
;   EXIT TO CPM
;
XIT:	CALL	CRLF		;DO CR.LF
	CALL	COFF		;TURN DRIVE/CTLR OFF
 	IF	TEST
	JMP	DEBUG		;IF WE ARE TESTING
 	ELSE
 	JMP	WBOOT		;WARM BOOT CPM
 	ENDIF




;	---GET NEW HEAD LIMITS---
;
;
NEWHED:	PRNT	MSG11		; 'START HEAD? '
	CALL	NHX		;GET HEAD NUM
	JNC	INV		;JIF INVALID HEAD NUM
	STA	TEMP		;SAVE NEW START HEAD
	PRNT	MSG12		; 'END HEAD? '
	CALL	NHX		;GET HEAD NUM
	JNC	INV		;JIF INVALID HEAD NUM
	INR	A		;FOR PROPER TESTING
	MOV	B,A		;B = END HEAD (+1)
	LDA	TEMP		;A = START HEAD
	CMP	B
	JNC	NH1		;JIF SH > EH
	MOV	L,A
	MOV	H,B
	SHLD	BGNHED		;SAVE NEW HEAD LIMITS
	JMP	LOOP		;DO NEXT CMD
; ERROR, START HEAD > END HEAD
NH1:	PRNT	MSG13		;PRINT ERROR MSG
	JMP	LOOP		;DO NEXT CMD
;
;   GET HEAD NUMBER
;
NHX:	MVI	A,2
	CALL	RCB		;INPUT HEAD NUM FROM OPER
	CALL	CONV		;CONVERT INPUT TO BINARY
	MOV	A,L
	CPI	MAXHD		;TEST HEAD NUM
	RET




;	---GET NEW CYLINDER LIMITS---
;
;
NEWCYL:	PRNT	MSG14		; 'START CYL? '
	CALL	NCX		;GET START CYL ADR
	JNC	INV		;JIF INVALID CYL ADR
	SHLD	TEMP		;SAVE CYL ADR
	PRNT	MSG15		; 'END CYL? '
	CALL	NCX		;GET END CYL ADR
	JNC	INV		;JIF INVALID CYL ADR
	INX	H		;FOR PROPER TESTING
	XCHG			;D/E = END CYL ADR
	LHLD	TEMP		;H/L = START CYL ADR
	CALL	TSUB		; (H/L) - (D/E)
	JNC	NC1		;JIF SC > EC
	SHLD	BGNCYL		;SAVE NEW START CYL ADR
	XCHG
	SHLD	ENDCYL		;SAVE NEW END CYL ADR
	JMP	LOOP		;DO NEXT CMD
; ERROR, START CYL > END CYL
NC1:	PRNT	MSG16		;PRINT ERROR MSG
	JMP	LOOP		;DO NEXT CMD
;
;   GET CYLINDER ADDRESS
;
NCX:	MVI	A,4
	CALL	RCB		;GET CYL ADR FROM OPER
	CALL	CONV		;CONVERT INPUT TO BINARY
	LXI	D,MAXCYL
	JMP	TSUB		;TEST CYL ADR, EXIT

	PAGE


;	=====================
;	** VERIFY THE DISK **
;	=====================




;	---VERIFY LOOP---
;
;
VERIFY:	CALL	CRLF		;DO CR.LF
	LXI	H,RDCODE
	CALL	SQUIRT		;LOAD READ M/CODE
	CALL	TKZ		;RESTORE
	CALL	SETUP		;SET START CYL/HEAD
	CALL	SEEK		;SEEK TO 1ST CYL
	CALL	NXP		;PRINT 1ST CYL ADR
;
VER1:	CALL	VAT		;VERIFY A TRACK
	CALL	STOP		;STOP VERIFY ?  (RIF NO)
	CALL	NXTK		;GOTO NEXT TRACK
	JC	VER1		;JIF MORE TO DO
	CALL	STZ		;SEEK TO TRACK ZERO
	PRNT	MSG9		; 'VERIFY DONE'
	JMP	LOOP		;DO NEXT CMD




;	---VERIFY A TRACK---
;
;
VAT:	LXI	H,SECTBL
	CALL	VHT		;READ EVEN SECTORS
	LXI	H,SECTBL+1	;..DO ODD SECTORS
;
;   READ HALF A TRACK
;
VHT:	SHLD	TBLADR		;SAVE SECTOR TABLE ADR
	MOV	A,M		;GET TABLE ENTRY
	STA	SECADR		;..SAVE IT
	INR	A		;TEST FOR DONE
	RZ			;RIF DONE
	MVI	A,VCNT
	STA	RTC		;SET RETRY COUNT
;
VHT1:	LXI	H,RTBL
	CALL	DORW		;READ A SECTOR
	LXI	H,RTC
	JZ	VHT2		;JIF READ OK
	DCR	M		;DECR RETRY COUNT
	JNZ	VHT1		;JIF RETRY READ
	CALL	HARD		;HARD ERROR, PRINT MSG
	JMP	VHT3
;
VHT2:	MOV	A,M		;A = RETRY COUNT
	SUI	VCNT		;TEST IT
	JZ	VHT3		;JIF HAD NO ERRORS
	CMA
	INR	A		;MAKE COUNT POSITIVE
	STA	RTC		;SAVE # RETRIES
	CALL	SOFT		;PRINT SOFT ERROR MSG
;
VHT3:	LHLD	TBLADR		;SECTOR TABLE ADR
	INX	H
	INX	H		;SKIP AN ENTRY
	JMP	VHT		;READ NEXT SECTOR

	PAGE


;	============================
;	** DISK RELATED FUNCTIONS **
;	============================




;	---EXECUTE READ/WRITE COMMANDS---
;
;
DORW:	CALL	RDY		;DRIVE READY ?  (RIF YES)
	MOV	A,M
	OUT	CTCSR		;ENB CMP BFR
	INX	H
	MOV	A,M
	OUT	CTBFR		;SET CMP BFR ADR
	INX	H
;
	XCHG			;D/E = TBL ADR
	LXI	H,CYL
	MVI	B,4
DO1:	MOV	A,M
	OUT	CTDP		;PUT HDR INFO INTO CMP BFR
	INX	H
	DCR	B
	JNZ	DO1
	XCHG			;H/L = TBL ADR
;
	MOV	A,M		;A = CNTL BANK
	INX	H
	MOV	B,A
	OUT	CTCSR		;SLCT CNTL BANK
	MOV	A,M
	OUT	CTBFR		;SET START ADR
	INX	H
	MOV	A,B
	ORI	START
	OUT	CTCSR		;START R/W CMD
;
DO3:	CALL	WFD		;WAIT FOR DONE
	STA	CSTAT		;SAVE CTLR STATUS
	ANI	0EH		;TEST FOR ERRORS
	MOV	B,A
	IN	DRCSR		;DRIVE STATUS
	STA	DSTAT		;  SAVE IT
	ANI	WRTFLT		;WRITE FAULT ?
	CNZ	CLRDF		;CIF CLEAR DRIVE FAULT
	ORA	B		;SET/CLEAR ERROR FLAG (0=OK)
	RET




;	---WAIT FOR DONE---
;
;
WFD:	LXI	H,0		;TIME-OUT DELAY COUNT
;
WFD1:	IN	CTCSR		;CTLR STATUS
	RRC
	JC	WFD2		;JIF DONE
	DCX	H		;DECR DELAY COUNT
	MOV	A,H
	ORA	L
	JNZ	WFD1		;JIF CON'T WAITING
	OUT	CTCSR		;STOP THE CTLR
	PRNT	MSG19		;PRINT ERROR MSG
	JMP	LOOP		;ABORT, TIME-OUT ERROR
;
WFD2:	IN	CTCSR		;GET CTLR STATUS
	MOV	B,A
	XRA	A
	OUT	CTCSR		;STOP THE CTLR
	MOV	A,B
	RET




;	---GOTO NEXT TRACK---
;
;
NXTK:	LHLD	BGNHED
	XCHG			;D = END HEAD, E = START HEAD
	LXI	H,HEAD
	INR	M		;INCR HEAD NUM
	MOV	A,M
	CMP	D
	JNC	NXT1		;JIF GOTO NEXT CYL
	CALL	HDSEL		;SLCT NEW HEAD
	STC			;SET FLAG = CON'T
	RET
;
NXT1:	MOV	M,E		;RESET HEAD NUM
	CALL	HDSEL		;SLCT NEW HEAD
	LHLD	ENDCYL
	XCHG			;D/E = END CYL ADR
	LHLD	CYL		;CURR CYL ADR
	INX	H
	SHLD	CYL		;SAVE NEW CYL ADR
	CALL	TSUB		; (H/L) - (D/E)
	RNC			;RIF TESTING DONE
	CALL	SEEK		;SEEK TO NEXT CYL
;
;   PRINT CURRENT CYLINDER/HEAD
;
NXP:	PRNT	MSG17		; 'CYL='
	LHLD	CYL
	CALL	P3D		;PRINT CYL ADR
	STC			;SET FLAG = CON'T TESTING
	RET




;	---RESTORE---
;
;
	IF	FASTKZ		;IF USE FAST RESTORE ALGORITHM

TKZ:	LXI	H,0
	SHLD	CCA		;INIT CURR CYL ADR
	IN	DRCSR		;DRIVE STATUS
	ANI	TK00		;TRACK ZERO FLAG
	RNZ			;RIF ALREADY AT TRACK ZERO
;
	CALL	RDY		;DRIVE READY ?  (RIF YES)
	MVI	A,MAXTKZ AND LMSK
	OUT	LOSC		;SET LSB OF SEEK COUNT
	MVI	A,MAXTKZ SHR 8
	OUT	HISC		;SET MSB
	MVI	A,SKOUT
	OUT	EXTCMD		;SET SEEK DIRC = OUTWARD
	MVI	A,SKCMD
	OUT	DRCSR		;ISSUE SEEK CMD
	LXI	H,0
	MVI	B,10		;INIT RETRY COUNT
;
TKZ1:	IN	DRCSR		;DRIVE STATUS
	ANI	TK00		;TRACK ZERO FLAG
	JNZ	TKZ2		;JIF AT TRACK ZERO
	DCX	H		;DECR TIME-OUT
	MOV	A,H
	ORA	L
	JNZ	TKZ1
	DCR	B
	JNZ	TKZ1
	OUT	HISC
	OUT	LOSC		;ZERO SEEK COUNTER
	PRNT	MSG4		; 'RESTORE FAILED'
	JMP	LOOP		;ABORT
;
TKZ2:	XRA	A
	OUT	HISC
	OUT	LOSC		;ZERO SEEK COUNTER
	JMP	WSC		;WAIT FOR SEEK DONE, EXIT

	ENDIF



	IF	NOT FASTKZ	;NORMAL RESTORE ALGORITHM

TKZ:	LXI	H,0
	SHLD	CCA		;SET CURR CYL ADR = ZERO
	LXI	B,MAXTKZ	;SET FIND COUNT
;
TKZ1:	CALL	RDY		;DRIVE READY ?  (RIF YES)
	IN	DRCSR		;DRIVE STATUS
	ANI	TK00		;TRACK ZERO INDICATOR
	RNZ			;RIF AT TRACK ZERO
	DCX	B		;DECR FIND COUNT
	MOV	A,B
	ORA	C
	JZ	TKZ2		;JIF REZERO FAILED
	XRA	A
	OUT	HISC		;CLEAR SEEK CNT, MSB
	INR	A
	OUT	LOSC		;SET SEEK COUNT = 1
	OUT	EXTCMD		;SET DIRC = OUT
	MVI	A,3
	OUT	DRCSR		;INITIATE STEP OUT
	CALL	WSC		;WAIT FOR SEEK DONE
	JMP	TKZ1
;
TKZ2:	PRNT	MSG4		; 'RESTORE FAILED'
	CALL	CRLF		;DO CR.LF
	JMP	LOOP		;DO NEXT CMD

	ENDIF




;	---RETURN TO TRACK ZERO---
;
;
STZ:	LXI	H,0
	SHLD	CYL		;SET TARGET CYL = ZERO
				;   * FALL THRU TO 'SEEK' *




;	---SEEK---
;
;
SEEK:	MVI	A,3	
	STA	SKRTC		;SET RETRY COUNT
;
SEK1:	CALL	RDY		;DRIVE READY ?  (RIF YES)
	LHLD	CYL		;TARGET CYL
	XCHG
	LHLD	CCA		;CURRENT CYL ADR
	CALL	SUBT		; (H/L) - (D/E)
	RZ			;RIF SAME CYL
	LDA	CHA		;CURRENT HEAD #
	MOV	B,A		;..SAVE FOR FUTURE USE
	MOV	A,H
	RAL
	JNC	SEK2		;JIF SEEK OUTWARD
; SEEK INWARD
	MOV	A,L		;MAKE SEEK COUNT POSITIVE
	CMA			  ;
	MOV	L,A		  ;
	MOV	A,H		  ;
	CMA			  ;
	MOV	H,A		  ;
	INX	H		  ;
	MOV	A,B
	ORI	SKIN
	OUT	EXTCMD		;SET SEEK DIRC = INWARD
	JMP	SEK3		;DO SEEK
; SEEK OUTWARD
SEK2:	MOV	A,B
	OUT	EXTCMD		;SET SEEK DIRC = OUTWARD
; 
SEK3:	MOV	A,L
	OUT	LOSC		;SET SEEK COUNT, LSB
	MOV	A,H
	OUT	HISC		;   * MSB
	MVI	A,3
	OUT	DRCSR		;START SEEK CMD
	LHLD	CYL
	SHLD	CCA		;UPDATE CURR CYL ADR
	CALL	WSC		;WAIT FOR SEEK DONE
; SEEK VERIFY
	MVI	A,3
	STA	VSRTC		;SET RETRY COUNT
	MVI	A,CBENB
	OUT	CTCSR		;ENABLE BANK ZERO CMP BFR
	MVI	A,VCA
	OUT	CTBFR		;SET CMP BFR ADR
	LHLD	CYL
	MOV	A,L
	OUT	CTDP		;SET CYL ADR, LSB
	MOV	A,H
	OUT	CTDP		;   * MSB
SEK4:	MVI	A,VSA
	OUT	CTBFR		;SET M/CODE START ADR
	MVI	A,START
	OUT	CTCSR		;START VERIFY
	CALL	WFD		;WAIT FOR DONE
	ANI	0CH		;TEST CTLR STATUS
	RZ			;RIF VERIFY OK
	LXI	H,VSRTC
	DCR	M		;DECR RETRY COUNT
	JNZ	SEK4		;JIF RETRY SEEK VERIFY
; VERIFY FAILED
	CALL	TKZ		;RESTORE
	LXI	H,SKRTC
	DCR	M		;DECR RETRY COUNT
	JNZ	SEK1		;JIF RETRY SEEK
; UNRECOVERABLE SEEK ERROR
	PRNT	MSG24		; 'SEEK FAILED'
	LHLD	CYL
	CALL	P3D		;PRINT CYL ADR
	CALL	CRLF		;DO CR.LF
	JMP	LOOP		;ABORT




;	---WAIT FOR SEEK COMPLETE---
;
;
WSC:	LXI	H,0		;TIME-OUT DELAY COUNT
	MVI	B,3
;
WSC1:	IN	DRCSR		;DRIVE STATUS
	RAL
	JC	WSC2		;JIF SEEK DONE
	DCX	H		;DECR RETRY COUNT
	MOV	A,H
	ORA	L
	JNZ	WSC1		;JIF CON'T WAITING
	DCR	B
	JNZ	WSC1		;JIF CON'T WAITING
	PRNT	MSG18		;PRINT ERROR MSG
	JMP	LOOP		;ABORT, TIME-OUT ERROR
;
WSC2:	RAR
	STA	DSTAT		;SAVE DRIVE STATUS
	RET




;	---HEAD SELECT---
;
;
HDSEL:	LDA	HEAD
	RLC			;SHIFT FOR H/W
	RLC
	ORI	1		;TO MAINTAIN DRIVE SLCT
