	CPI	ESC		;"ESC" KEY ?
	RNZ			;NO, EXIT
	PRNT	MSG8		; 'VERIFY ABORTED'
	CALL	PCA		;PRINT CYL ADR
	CALL	PHN		;PRINT HEAD #
	CALL	CRLF		;DO CR.LF
	CALL	STZ		;MOVE HEADS BACK TO TRACK 00
	JMP	LOOP		;ABORT, DO NEXT CMD




